// testdata/hunter-marksmanship.json is a real, committed output of this
// command (go run ./sim/cmd/leveling-bis -spec hunter-marksmanship
// -bands 20,40,60 -weights-iterations 5 -out sim/cmd/leveling-bis/testdata),
// kept small (three bands, five weights iterations) on purpose - this
// lane's brief only asks for a fixture the schema test can round-trip,
// not a realistic nightly-quality run (that is what `make bis` writes
// to data/builds/<build>/bis, never committed from a dev machine - see
// this lane's report).
const fixturePath = "testdata/hunter-marksmanship.json"

// TestSpecReportFixtureRoundTrips is the schema test this lane's brief
// asks for: the committed fixture decodes into specReport, and
// re-encoding that value reproduces byte-identical JSON - proof the Go
// struct is a lossless, exact match for what writeSpecReport emits
// (lane bis-web's read contract), not just "close enough to decode".
func TestSpecReportFixtureRoundTrips(t *testing.T) {
	original, err := os.ReadFile(fixturePath)
	if err != nil {
		t.Fatalf("reading %s: %v", fixturePath, err)
	}

	var decoded specReport
	if err := json.Unmarshal(original, &decoded); err != nil {
		t.Fatalf("decoding %s into specReport: %v", fixturePath, err)
	}

	if decoded.Spec != "hunter-marksmanship" {
		t.Errorf("Spec = %q, want %q", decoded.Spec, "hunter-marksmanship")
	}
	if decoded.Build == "" {
		t.Error("Build is empty")
	}
	if decoded.EngineVersion == "" {
		t.Error("EngineVersion is empty")
	}
	if decoded.GeneratedAt == "" {
		t.Error("GeneratedAt is empty")
	}
	if len(decoded.Bands) == 0 {
		t.Fatal("Bands is empty")
	}
	for _, band := range decoded.Bands {
		if len(band.Slots) != len(slotOrder) {
			t.Errorf("band %d %s: %d slot rows, want %d (one per slotOrder entry)", band.Band, band.Faction, len(band.Slots), len(slotOrder))
		}
		if len(band.Weights) == 0 {
			t.Errorf("band %d %s: Weights is empty", band.Band, band.Faction)
		}
	}

	reencoded, err := json.MarshalIndent(decoded, "", "  ")
	if err != nil {
		t.Fatalf("re-encoding: %v", err)
	}

	var reDecoded specReport
	if err := json.Unmarshal(reencoded, &reDecoded); err != nil {
		t.Fatalf("decoding the re-encoded JSON: %v", err)
	}
	if !reflect.DeepEqual(decoded, reDecoded) {
		t.Fatal("decode -> encode -> decode did not reproduce the same value: the schema is lossy somewhere")
	}

	// Byte-identical is the stronger claim: writeSpecReport's own
	// json.MarshalIndent(out, "", "  ") call uses the same indent this
	// test does, so a fixture generated by this command's own writer
	// should re-encode to the exact bytes it was written with (modulo
	// the fixture never being re-formatted by hand).
	if string(reencoded) != string(original) {
		t.Error("re-encoding the decoded fixture did not reproduce the original bytes - either the fixture was hand-edited/reformatted, or specReport's field order/tags drifted from writeSpecReport's own output")
	}
}

// TestPublishedRatingFamilyWeightRowsSatisfyTheirOwnContract is this
// lane's brief, item 3's own contract test: for every published
// rating-family row (RatingFactor set), Weight == WeightPerPercent /
// RatingFactor must hold exactly - the row's own numbers must be
// internally consistent, not just individually plausible. Run
// directly against the committed fixture (regenerated by this lane so
// it already carries these fields), so this is also a regression test
// against a real run's own output, not only a hand-built unit case.
func TestPublishedRatingFamilyWeightRowsSatisfyTheirOwnContract(t *testing.T) {
	b, err := os.ReadFile(fixturePath)
	if err != nil {
		t.Fatalf("reading %s: %v", fixturePath, err)
	}
	var decoded specReport
	if err := json.Unmarshal(b, &decoded); err != nil {
		t.Fatalf("decoding %s: %v", fixturePath, err)
	}
	checked := 0
	for _, band := range decoded.Bands {
		for _, w := range band.Weights {
			if w.RatingFactor == 0 {
				continue
			}
			if w.Unit != "rating" {
				t.Errorf("band %d %s stat %s: rating_factor set but unit = %q, want \"rating\"", band.Band, band.Faction, w.Stat, w.Unit)
			}
			want := w.WeightPerPercent / w.RatingFactor
			if w.Weight != want {
				t.Errorf("band %d %s stat %s: weight = %v, want weight_per_percent/rating_factor = %v", band.Band, band.Faction, w.Stat, w.Weight, want)
			}
			checked++
		}
	}
	if checked == 0 {
		t.Fatal("no rating-family weight row (rating_factor set) found in the fixture - the fixture no longer exercises this contract")
	}
}

// TestPublishWeightRatingUnitsConvertsOnlyRatingFamilyRows is the
// function-level unit test alongside the fixture-level contract test
// above: a hand-built row set pins the exact conversion (weight AND
// error divide by the factor, weight_per_percent keeps the original)
// and that a non-rating-family stat passes through with
// weight_per_percent set but unit/rating_factor left unset.
func TestPublishWeightRatingUnitsConvertsOnlyRatingFamilyRows(t *testing.T) {
	rows := []weightRow{
		{Stat: "crit", Weight: 18.2, Error: 3.5, Insignificant: false},
		{Stat: "agility", Weight: 2.0, Error: 0.1, Insignificant: false},
	}
	factors := ratingFactors{"crit": 14, "hit": 10}

	got := publishWeightRatingUnits(rows, factors)

	crit := got[0]
	if crit.Unit != "rating" || crit.RatingFactor != 14 {
		t.Errorf("crit row = %+v, want unit=rating rating_factor=14", crit)
	}
	if crit.Weight != 18.2/14 || crit.Error != 3.5/14 {
		t.Errorf("crit row weight/error = %v/%v, want %v/%v", crit.Weight, crit.Error, 18.2/14, 3.5/14)
	}
	if crit.WeightPerPercent != 18.2 {
		t.Errorf("crit row weight_per_percent = %v, want the original sim-unit weight 18.2", crit.WeightPerPercent)
	}

	agility := got[1]
	if agility.Unit != "" || agility.RatingFactor != 0 {
		t.Errorf("agility row = %+v, want no unit/rating_factor (not a rating-family stat)", agility)
	}
	if agility.Weight != 2.0 || agility.WeightPerPercent != 2.0 {
		t.Errorf("agility row weight/weight_per_percent = %v/%v, want 2.0/2.0 (unchanged)", agility.Weight, agility.WeightPerPercent)
	}

	// Immutability: the input slice's own rows are untouched.
	if rows[0].Weight != 18.2 || rows[0].Unit != "" {
		t.Errorf("publishWeightRatingUnits mutated its input: %+v", rows[0])
	}
}

// TestDedupeAlternativesCollapsesByNameToo is this lane's brief, item
// 3: "Signet Ring of the Bronze Dragonflight" published twice in the
// same band-60 finger1 Alternatives list under two different item
// ids (the same shape Sentinel's/Scout's Medallion, Highlander's/
// Defiler's Leather Girdle and Sentinel's Chain Leggings share) -
// dedupeAlternatives already collapsed a shared ID (Grand Marshal's
// Stave); it must also collapse a shared NAME across two DIFFERENT
// ids, keeping the better-ranked row (betterAlternative's own rule),
// the same way it already does for ID.
func TestDedupeAlternativesCollapsesByNameToo(t *testing.T) {
	rows := []alternativeRow{
		{ItemID: 19147, ItemName: "Signet Ring of the Bronze Dragonflight", DPSDelta: -1.2},
		{ItemID: 19148, ItemName: "Signet Ring of the Bronze Dragonflight", DPSDelta: -0.4},
	}
	got := dedupeAlternatives(rows)
	if len(got) != 1 {
		t.Fatalf("dedupeAlternatives(%+v) = %+v, want exactly 1 row (same name, two ids)", rows, got)
	}
	if got[0].ItemID != 19148 {
		t.Errorf("dedupeAlternatives kept item id %d, want 19148 (the higher DPSDelta row, betterAlternative's own rule)", got[0].ItemID)
	}
}

// TestDedupeAlternativesNameCollapseRunsAfterIDCollapse guards the
// order: two rows sharing BOTH an id and a name (the ordinary case,
// every alternative in practice) must still collapse to exactly one
// row, not be treated as "already distinct because the ID pass ran
// first and left one row per id, so the name pass finds nothing to
// do" - the two passes compose, they do not each have to independently
// find every duplicate on their own axis.
func TestDedupeAlternativesNameCollapseRunsAfterIDCollapse(t *testing.T) {
	rows := []alternativeRow{
		{ItemID: 500, ItemName: "Grand Marshal's Stave", DPSDelta: 0, SourceKind: "vendor"},
		{ItemID: 500, ItemName: "Grand Marshal's Stave", DPSDelta: 0, SourceKind: "pvp"},
	}
	got := dedupeAlternatives(rows)
	if len(got) != 1 {
		t.Fatalf("dedupeAlternatives(%+v) = %+v, want exactly 1 row", rows, got)
	}
	if got[0].SourceKind != "pvp" {
		t.Errorf("dedupeAlternatives kept SourceKind %q, want \"pvp\" (betterAlternative's own tie-break)", got[0].SourceKind)
	}
}

// TestDedupeAlternativesDistinctNamesSurviveBoth pins the boundary:
// two rows with DIFFERENT ids and DIFFERENT names are two genuinely
// different items and must both survive - neither pass may collapse
// unrelated alternatives just because they happen to share a slot.
func TestDedupeAlternativesDistinctNamesSurviveBoth(t *testing.T) {
	rows := []alternativeRow{
		{ItemID: 1, ItemName: "Band of Circling Vultures", DPSDelta: -0.5},
		{ItemID: 2, ItemName: "Master Dragonslayer's Ring", DPSDelta: -0.8},
	}
	got := dedupeAlternatives(rows)
	if len(got) != 2 {
		t.Fatalf("dedupeAlternatives(%+v) = %+v, want both distinct rows kept", rows, got)
	}
}
