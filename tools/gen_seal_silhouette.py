#!/usr/bin/env python3
# /// script
# requires-python = ">=3.11"
# dependencies = ["skia-pathops>=0.9", "fonttools>=4.50"]
# ///
"""Emit the Android one-colour seal drawables from the flat seal.

The source is design/assets/brand/seal-flat/seal-flat-tiny-bold.svg (the seal without the
swash, bold LX). The silhouette is the seal's whole disc with the LX knocked out, the letters
taken with their dark outline so they keep the bold weight they have in the mark. Nothing is
redrawn: the disc is the seal's own outer edge and the letters are its own path and stroke.

Two drawables come out of the one silhouette:
- res/drawable/ic_notification_seal.xml: the notification small icon, 24 dp with the 22 dp live
  area of the status-bar icon grid.
- res/drawable/ic_launcher_monochrome.xml: the adaptive icon's themed (monochrome) layer, on the
  108 dp canvas with the seal inside the 66 dp safe zone.

usage: uv run tools/gen_seal_silhouette.py
"""
import math
import re
from pathlib import Path

import pathops
from fontTools.misc.transform import Transform
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.svgLib.path import parse_path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "design/assets/brand/seal-flat/seal-flat-tiny-bold.svg"
DRAWABLES = ROOT / "apps/android/app/src/main/res/drawable"

# The source canvas and the seal's outer edge (the outer ring's radius plus half its stroke).
CANVAS = 512.0
SEAL_RADIUS = 256.0
# The letter group's transforms, outermost first, exactly as the SVG nests them.
LETTER_TRANSFORMS = (
    Transform().translate(256.0, 256.0).scale(1.01053).translate(-263.25, -240.0),
    Transform().translate(0, 512).scale(0.125, -0.125),
)
# The letters' outline stroke, in the path's own units, as the SVG draws it.
LETTER_STROKE = 95.0
# Cubic control-point distance for a quarter circle.
KAPPA = 4 * (math.sqrt(2) - 1) / 3


def attr(svg: str, pattern: str) -> str:
    match = re.search(pattern, svg)
    if not match:
        raise SystemExit(f"{SOURCE.name}: no match for {pattern!r}; the seal source changed shape")
    return match.group(1)


def letters(svg: str) -> pathops.Path:
    """The LX with its outline stroke, in source canvas units."""
    raw = pathops.Path()
    parse_path(attr(svg, r' d="([^"]+)"'), raw.getPen())
    outline = pathops.Path(raw)
    outline.stroke(LETTER_STROKE, pathops.LineCap.BUTT_CAP, pathops.LineJoin.ROUND_JOIN, 4)
    # Round joins come out as conics, which the boolean ops do not take.
    outline.convertConicsToQuads()
    local = pathops.op(raw, outline, pathops.PathOp.UNION)
    placed = pathops.Path()
    transform = LETTER_TRANSFORMS[0].transform(LETTER_TRANSFORMS[1])
    local.draw(TransformPen(placed.getPen(), transform))
    return placed


def disc(cx: float, cy: float, r: float) -> pathops.Path:
    path = pathops.Path()
    k = r * KAPPA
    path.moveTo(cx + r, cy)
    path.cubicTo(cx + r, cy + k, cx + k, cy + r, cx, cy + r)
    path.cubicTo(cx - k, cy + r, cx - r, cy + k, cx - r, cy)
    path.cubicTo(cx - r, cy - k, cx - k, cy - r, cx, cy - r)
    path.cubicTo(cx + k, cy - r, cx + r, cy - k, cx + r, cy)
    path.close()
    return path


def silhouette() -> pathops.Path:
    svg = SOURCE.read_text(encoding="utf-8")
    centre = CANVAS / 2
    return pathops.op(disc(centre, centre, SEAL_RADIUS), letters(svg), pathops.PathOp.DIFFERENCE)


def path_data(shape: pathops.Path, viewport: float, diameter: float) -> str:
    """The silhouette scaled to `diameter` and centred in a square `viewport`."""
    scale = diameter / (2 * SEAL_RADIUS)
    offset = (viewport - diameter) / 2
    pen = SVGPathPen(None, ntos=lambda v: f"{v:.3f}".rstrip("0").rstrip("."))
    shape.draw(TransformPen(pen, Transform().translate(offset, offset).scale(scale)))
    return pen.getCommands()


def vector(comment: str, size_dp: int, viewport: float, diameter: float, shape: pathops.Path) -> str:
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!--
{comment}
    Generated by tools/gen_seal_silhouette.py from
    design/assets/brand/seal-flat/seal-flat-tiny-bold.svg; edit the generator, not this file.
-->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size_dp}dp" android:height="{size_dp}dp"
    android:viewportWidth="{viewport:g}" android:viewportHeight="{viewport:g}">
    <path android:fillColor="#FFFFFFFF"
        android:pathData="{path_data(shape, viewport, diameter)}" />
</vector>
"""


NOTIFICATION = (
    "ic_notification_seal.xml",
    """    The notification small icon: the flat LX seal as one white disc with the letters knocked
    out, which the system tints. 22 dp across inside the 24 dp status-bar grid.""",
    24, 24.0, 22.0,
)
MONOCHROME = (
    "ic_launcher_monochrome.xml",
    """    The adaptive icon's themed layer (Android 13+): the same silhouette as the notification
    icon, which the launcher tints. 64 dp across, inside the 66 dp safe zone of the 108 dp canvas.""",
    108, 108.0, 64.0,
)


def main() -> None:
    shape = silhouette()
    for name, comment, size_dp, viewport, diameter in (NOTIFICATION, MONOCHROME):
        (DRAWABLES / name).write_text(vector(comment, size_dp, viewport, diameter, shape), encoding="utf-8")
        print(f"wrote {DRAWABLES.relative_to(ROOT) / name}")


if __name__ == "__main__":
    main()
