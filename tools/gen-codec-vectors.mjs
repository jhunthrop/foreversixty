// tools/gen-codec-vectors.mjs
// The shared codec fixture vectors, written to both lanes at once.
//
// The FS1 vectors are produced by the site's own decoder -- web/src/lib/planner/fs1.ts,
// which has shipped and is tested -- so the addon's Lua codec is held to the
// implementation the planner already trusts rather than to a second reading of the
// grammar. The FSB1 vectors are hand-written here because no implementation of that
// format exists yet in either language: they are the specification both lanes code to.
//
// Run: node tools/gen-codec-vectors.mjs
import { writeFileSync } from 'node:fs';
import { decodeFS1 } from '../web/src/lib/planner/fs1.ts';

const FS1_CODES = [
  ['version 1, one tree, two slots', 'FS1:1.60.1.69893:paladin:human:503200000/0/0:head=12640,chest=11726'],
  ['version 1, no gear', 'FS1:1.60.1.69893:mage:gnome:0/0/5500000000000000005:'],
  ['version 2, enchant and suffix on a slot', 'FS1:1.60.1.69893:rogue:orc:0/553/0:main_hand=19865:2564:1825,off_hand=17075'],
  ['version 2, bags and bank', 'FS1:1.60.1.69893:warrior:tauren:5/0/0:head=12640|bags=11726,19865:2564|bank=12640,11726'],
  ['version 2, a named set and a named loadout', 'FS1:1.60.1.69893:druid:night-elf:5/0/0:head=12640|sets=Tank=head=12640|loadouts=Deep%20Feral=0/553/0'],
  ['version 2, professions', 'FS1:1.60.1.69893:priest:human:0/0/5:|professions=enchanting,tailoring'],
  ['version 2, an unknown section is ignored and named', 'FS1:1.60.1.69893:priest:human:0/0/5:|pets=1,2'],
];

const INVALID = [
  ['a foreign prefix', 'FS2:1.60.1.69893:paladin:human:0/0/0:'],
  ['no prefix at all', 'paladin:human'],
  ['two trees instead of three', 'FS1:1.60.1.69893:paladin:human:5/0:'],
  ['a slot this planner does not have', 'FS1:1.60.1.69893:paladin:human:0/0/0:tabard=12640'],
  ['a gear entry with two equals signs', 'FS1:1.60.1.69893:paladin:human:0/0/0:head=12640=99'],
  ['a non-numeric item id', 'FS1:1.60.1.69893:paladin:human:0/0/0:head=12640abc'],
  ['too few fields', 'FS1:1.60.1.69893:paladin'],
];

// The FSB1 grammar (design "Formats"), the only statement of it that both lanes read:
//   FSB1:<data-build>:<class-slug>:<order>:<gear>
//   <order> = one triple per point spent, tab/tier/column, each one base-36 character,
//             all 1-based, concatenated with no separator.
//   <gear>  = entries joined by ",", each <slot>=<item_id>[:<stat>=<value>[;<stat>=<value>]…]
const FSB1 = [
  {
    name: 'three points, one item with two stats',
    code: 'FSB1:1.60.1.69893:paladin:111112121:head=12640:stamina=17;spell_power=23',
    build: {
      dataBuild: '1.60.1.69893',
      classSlug: 'paladin',
      order: [
        { tab: 1, tier: 1, column: 1 },
        { tab: 1, tier: 1, column: 2 },
        { tab: 1, tier: 2, column: 1 },
      ],
      gear: [{ slot: 'head', itemId: 12640, stats: { stamina: 17, spell_power: 23 } }],
    },
  },
  {
    name: 'a point in the third tab at tier 7, column 1',
    code: 'FSB1:1.60.1.69893:warrior:371:',
    build: {
      dataBuild: '1.60.1.69893',
      classSlug: 'warrior',
      order: [{ tab: 3, tier: 7, column: 1 }],
      gear: [],
    },
  },
  {
    name: 'two items, one with no stats',
    code: 'FSB1:1.60.1.69893:rogue::main_hand=19865:attack_power=30,off_hand=17075',
    build: {
      dataBuild: '1.60.1.69893',
      classSlug: 'rogue',
      order: [],
      gear: [
        { slot: 'main_hand', itemId: 19865, stats: { attack_power: 30 } },
        { slot: 'off_hand', itemId: 17075, stats: {} },
      ],
    },
  },
];

const FSB1_INVALID = [
  ['a foreign prefix', 'FS1:1.60.1.69893:paladin:111:'],
  ['an order that is not a multiple of three', 'FSB1:1.60.1.69893:paladin:1111:'],
  ['a tab index of zero', 'FSB1:1.60.1.69893:paladin:011:'],
  ['a slot this planner does not have', 'FSB1:1.60.1.69893:paladin::tabard=12640'],
  ['a stat with no value', 'FSB1:1.60.1.69893:paladin::head=12640:stamina'],
  ['a non-numeric stat value', 'FSB1:1.60.1.69893:paladin::head=12640:stamina=lots'],
];

const fs1 = FS1_CODES.map(([name, code]) => {
  const result = decodeFS1(code);
  if (!result.ok) throw new Error(`${name}: the site's own decoder refused it: ${result.message}`);
  const { gear, ...build } = result.build; // `gear` is the lossy slot->id map; gearSlots is the truth
  return { name, code, build };
});

const fs1Invalid = INVALID.map(([name, code]) => {
  const result = decodeFS1(code);
  if (result.ok) throw new Error(`${name}: the site's own decoder accepted it`);
  return { name, code, message: result.message };
});

const vectors = {
  note: 'Generated by tools/gen-codec-vectors.mjs. Two byte-identical copies: addon/tests/fixtures/ and web/src/fixtures/addon/.',
  fs1,
  fs1Invalid,
  fsb1: FSB1,
  fsb1Invalid: FSB1_INVALID.map(([name, code]) => ({ name, code })),
};

const json = JSON.stringify(vectors, null, 2) + '\n';
// Resolved against this file, never against the working directory: the script is run
// from web/ (that is where tsx and the TypeScript config live) and a relative path
// would land the fixtures under web/addon/.
for (const relative of ['../addon/tests/fixtures/codec-vectors.json', '../web/src/fixtures/addon/codec-vectors.json']) {
  const target = new URL(relative, import.meta.url);
  writeFileSync(target, json);
  console.log(`wrote ${target.pathname}`);
}
