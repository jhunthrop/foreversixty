package main

import (
	"bytes"
	"fmt"
	"go/format"
)

type catalogueFile struct {
	Entries []entry `json:"entries"`
}

type entry struct {
	Key       string     `json:"key"`
	Name      string     `json:"name"`
	Kind      string     `json:"kind"`
	SpellID   int        `json:"spell_id"`
	Need      need       `json:"need"`
	Pool      string     `json:"pool"`
	Providers []provider `json:"providers"`
}

type need struct {
	Count int    `json:"count"`
	Per   string `json:"per"`
}

type provider struct {
	Class  string `json:"class"`
	Spec   string `json:"spec"`
	Talent string `json:"talent"`
	Spell  int    `json:"spell"`
}

// icon is the row's stem: its own spell's, else the first provider spell that has one (a
// judgement debuff draws its seal's art).
func (e entry) icon(ix iconIndex) string {
	if stem := ix.of(e.SpellID); stem != "" {
		return stem
	}
	for _, p := range e.Providers {
		if stem := ix.of(p.Spell); p.Spell != 0 && stem != "" {
			return stem
		}
	}
	return ""
}

func goSource(build string, entries []entry, ix iconIndex) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by cmd/genraidcover from data/curated/raid-cover.json and data/builds/%s. DO NOT EDIT.\n\n", build)
	b.WriteString("package guilds\n\n")
	b.WriteString("// raidCoverBuild is the client build the icons were read from.\n")
	fmt.Fprintf(&b, "const raidCoverBuild = %q\n\n", build)
	b.WriteString("// raidCoverCatalogue is data/curated/raid-cover.json, in its order.\n")
	b.WriteString("var raidCoverCatalogue = []coverEntry{\n")
	for _, e := range entries {
		stem := e.icon(ix)
		if stem == "" {
			return nil, fmt.Errorf("%s: no icon for spell %d in build %s", e.Key, e.SpellID, build)
		}
		fmt.Fprintf(&b, "\t{Key: %q, Name: %q, Kind: %q, SpellID: %d, Icon: %q, Need: coverNeed{Count: %d, Per: %q}, Pool: %q, Providers: []coverProvider{",
			e.Key, e.Name, e.Kind, e.SpellID, stem, e.Need.Count, e.Need.Per, e.Pool)
		for _, p := range e.Providers {
			fmt.Fprintf(&b, "{Class: %q, Spec: %q, Talent: %q, Spell: %d},", p.Class, p.Spec, p.Talent, p.Spell)
		}
		b.WriteString("}},\n")
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}
