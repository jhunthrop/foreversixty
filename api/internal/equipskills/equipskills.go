// Package equipskills reads data/builds/<build>/equip-skills.json (data/pipeline/equip_skills.py:
// which weapons and armour each class can equip, from what level, from the client's SkillLine,
// SkillLineAbility and SkillRaceClassInfo) and renders it as the Go table the guild Loot tab reads
// (api/internal/guilds/equip_rules_table.go). The API image carries no data/builds, so the table
// is copied into Go; cmd/genequiprules writes it and a guilds test pins the two.
package equipskills

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"go/format"
	"sort"
)

// Skill is one weapon or armour skill a class learns: the item subclass it gates, the client's
// name for it and the level it is learned at.
type Skill struct {
	Subclass int    `json:"subclass"`
	Skill    string `json:"skill"`
	Level    int    `json:"level"`
}

// Class is one class's equip skills. DualWieldLevel is nil for a class that never dual wields.
type Class struct {
	Armor          []Skill `json:"armor"`
	Weapons        []Skill `json:"weapons"`
	DualWieldLevel *int    `json:"dual_wield_level"`
}

// Doc is the whole file.
type Doc struct {
	Build   string           `json:"build"`
	Source  []string         `json:"source"`
	Classes map[string]Class `json:"classes"`
}

// SourcePath is the repo-relative path of build's file, as the generated table names its source.
func SourcePath(build string) string {
	return "data/builds/" + build + "/equip-skills.json"
}

// Parse decodes an equip-skills.json body, refusing one with no build or no classes.
func Parse(body []byte) (Doc, error) {
	var doc Doc
	if err := json.Unmarshal(body, &doc); err != nil {
		return Doc{}, fmt.Errorf("equipskills: %w", err)
	}
	if doc.Build == "" || len(doc.Classes) == 0 {
		return Doc{}, errors.New("equipskills: the file names no build or no classes")
	}
	return doc, nil
}

// GoSource renders doc as the guilds package's generated table: equipSkillsBuild and
// equipSkills, map class slug -> equipClass (subclass -> learn level per kind; dualWieldLevel 0
// for never). The output is gofmt'd.
func GoSource(doc Doc, sourcePath string) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by cmd/genequiprules from %s. DO NOT EDIT.\n\n", sourcePath)
	b.WriteString("package guilds\n\n")
	fmt.Fprintf(&b, "// equipSkillsBuild is the client build the table was read from.\nconst equipSkillsBuild = %q\n\n", doc.Build)
	b.WriteString("// equipSkills is, per class, the item subclasses it can equip and the level it learns each at.\n")
	b.WriteString("var equipSkills = map[string]equipClass{\n")
	slugs := make([]string, 0, len(doc.Classes))
	for slug := range doc.Classes {
		slugs = append(slugs, slug)
	}
	sort.Strings(slugs)
	for _, slug := range slugs {
		c := doc.Classes[slug]
		fmt.Fprintf(&b, "%q: {\narmor: %s,\nweapons: %s,\n", slug, levelMap(c.Armor), levelMap(c.Weapons))
		if c.DualWieldLevel != nil {
			fmt.Fprintf(&b, "dualWieldLevel: %d,\n", *c.DualWieldLevel)
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

// levelMap is skills as a map[int]int literal (subclass -> level, with the skill's name as a
// comment), in subclass order.
func levelMap(skills []Skill) string {
	sorted := append([]Skill(nil), skills...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].Subclass < sorted[j].Subclass })
	var b bytes.Buffer
	b.WriteString("map[int]int{\n")
	for _, s := range sorted {
		fmt.Fprintf(&b, "%d: %d, // %s\n", s.Subclass, s.Level, s.Skill)
	}
	b.WriteString("}")
	return b.String()
}
