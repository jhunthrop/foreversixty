// Package raidbosses reads data/builds/<build>/raid-bosses.json (data/pipeline/raid_bosses.py:
// the first raid tier's bosses and their loot, tied to the client's own Map, DungeonEncounter and
// Journal rows by name) and renders it as the Go table the guild loot picker and raid assignment
// templates read (api/internal/guilds/raid_bosses_table.go). The API image carries no data/builds,
// so the table is copied into Go; cmd/genraidbosses writes it and a guilds test pins the two.
package raidbosses

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"go/format"
	"strings"
)

// InClient is the status of a raid the client names; any other raid has no bosses to copy.
const InClient = "in_client"

// Item is one boss drop, with the build's items.json fields the loot picker reads.
type Item struct {
	ItemID        int    `json:"item_id"`
	Name          string `json:"name"`
	Quality       int    `json:"quality"`
	ItemLevel     int    `json:"item_level"`
	RequiredLevel int    `json:"required_level"`
	ClassID       int    `json:"class_id"`
	SubclassID    int    `json:"subclass_id"`
	InventoryType int    `json:"inventory_type"`
}

// Boss is one DungeonEncounter row and its loot. JournalEncounterID is nil when the client ships
// no journal row for it; LootSource names where the loot came from.
type Boss struct {
	EncounterID        int64   `json:"encounter_id"`
	JournalEncounterID *int64  `json:"journal_encounter_id"`
	Name               string  `json:"name"`
	Order              int     `json:"order"`
	LootSource         *string `json:"loot_source"`
	Loot               []Item  `json:"loot"`
}

// Raid is one first-tier raid.
type Raid struct {
	Key        string  `json:"key"`
	Name       string  `json:"name"`
	Status     string  `json:"status"`
	Note       *string `json:"note"`
	MaxPlayers *int    `json:"max_players"`
	Bosses     []Boss  `json:"bosses"`
}

// Doc is the whole file.
type Doc struct {
	Build string `json:"build"`
	Raids []Raid `json:"raids"`
}

// SourcePath is the repo-relative path of build's file, as the generated table names its source.
func SourcePath(build string) string {
	return "data/builds/" + build + "/raid-bosses.json"
}

// Parse decodes a raid-bosses.json body, refusing one with no build, no raids, or a raid in the
// client with no bosses.
func Parse(body []byte) (Doc, error) {
	var doc Doc
	if err := json.Unmarshal(body, &doc); err != nil {
		return Doc{}, fmt.Errorf("raidbosses: %w", err)
	}
	if doc.Build == "" || len(doc.Raids) == 0 {
		return Doc{}, errors.New("raidbosses: the file names no build or no raids")
	}
	for _, r := range doc.Raids {
		if r.Status == InClient && len(r.Bosses) == 0 {
			return Doc{}, fmt.Errorf("raidbosses: %s is in the client but has no bosses", r.Key)
		}
	}
	return doc, nil
}

// GoSource renders doc as the guilds package's generated table: raidBossesBuild and
// firstTierRaids, the raids the client names in curated order, each boss in the client's order
// with its loot. A raid the client does not name is listed in a comment only. gofmt'd.
func GoSource(doc Doc, sourcePath string) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by cmd/genraidbosses from %s. DO NOT EDIT.\n\n", sourcePath)
	b.WriteString("package guilds\n\n")
	fmt.Fprintf(&b, "// raidBossesBuild is the client build the table was read from.\nconst raidBossesBuild = %q\n\n", doc.Build)
	var absent []string
	for _, r := range doc.Raids {
		if r.Status != InClient {
			absent = append(absent, fmt.Sprintf("%s (%s)", r.Name, r.Status))
		}
	}
	b.WriteString("// firstTierRaids is each first-tier raid the client names, with its bosses and their loot.\n")
	if len(absent) > 0 {
		fmt.Fprintf(&b, "// Not in this client, so absent: %s.\n", strings.Join(absent, ", "))
	}
	b.WriteString("var firstTierRaids = []tierRaid{\n")
	for _, r := range doc.Raids {
		if r.Status == InClient {
			writeRaid(&b, r)
		}
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

func writeRaid(b *bytes.Buffer, r Raid) {
	maxPlayers := 0
	if r.MaxPlayers != nil {
		maxPlayers = *r.MaxPlayers
	}
	fmt.Fprintf(b, "{Key: %q, Name: %q, MaxPlayers: %d, Bosses: []tierBoss{\n", r.Key, r.Name, maxPlayers)
	for _, boss := range r.Bosses {
		var journal int64
		if boss.JournalEncounterID != nil {
			journal = *boss.JournalEncounterID
		}
		source := ""
		if boss.LootSource != nil {
			source = *boss.LootSource
		}
		fmt.Fprintf(b, "{EncounterID: %d, JournalEncounterID: %d, Name: %q, Order: %d, LootSource: %q, Loot: []tierItem{\n",
			boss.EncounterID, journal, boss.Name, boss.Order, source)
		for _, it := range boss.Loot {
			fmt.Fprintf(b, "{ItemID: %d, Name: %q, Quality: %d, ItemLevel: %d, RequiredLevel: %d, ItemClass: %d, Subclass: %d, InventoryType: %d},\n",
				it.ItemID, it.Name, it.Quality, it.ItemLevel, it.RequiredLevel, it.ClassID, it.SubclassID, it.InventoryType)
		}
		b.WriteString("}},\n")
	}
	b.WriteString("}},\n")
}
