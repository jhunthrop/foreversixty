"""The owner's paperdoll frame, cleaned and measured (design/specs/2026-11-09-directions.md, Paperdoll).

Source: design/assets/art/paperdoll-frame-source.jpeg (generated by the owner, explicit choice; 1792 x 2400). It has a
baked-in checkerboard where the transparency should be, and fake writing and map scratches in its teal centre.

    python3 design/mocks/directions/paperdoll_asset.py
    -> paperdoll/frame@1x.{webp,png} (896 x 1200), frame@2x.{webp,png} (1792 x 2400), paperdoll/slots.json

Cleaning:
- alpha: the checkerboard is near-grey and light (channel spread under 16, minimum over 175) and connected to the image
  edge; that region becomes transparent, its edge feathered by one pixel. The frame's own highlights are gold (saturated),
  so they are never caught.
- centre: the frame's own marble stays (owner 2026-11-09); the fake writing and map rings drawn on it, thin dark
  strokes, are closed out of it (a grey closing), and the gold knot corners stay.
Measuring: each slot's inner teal rectangle, refined from its predicted box by the first and last rows and columns where
teal covers more than a fifth of the line (the glyphs never span a slot's edge). Stored as percentages of the frame.
"""
import json
from pathlib import Path

import numpy as np
from PIL import Image, ImageFilter
from scipy import ndimage

from assets import owner_asset

HERE = Path(__file__).resolve().parent
OUT = HERE / 'paperdoll'
SOURCE = 'art/paperdoll-frame-source.jpeg'
CHECKER_SPREAD, CHECKER_MIN = 16, 175
# The centre's content box: inset from the knot border's inner gold line (inner_box) by CENTRE_INSET on every side, so
# the tooltip and its link sit centred between the frame's inner edges.
CENTRE_INSET = 2
# Cleaned: everything inside the knot border's inner gold line. The fake writing's strokes are under 15 px wide.
STROKE_PX = 15
MARBLE_BLUR = 3
# Predicted slot boxes (source px): columns, the 211 px row rhythm, the weapon row; refined by refine().
LEFT_X, RIGHT_X, SLOT_W, SLOT_H, ROW0, ROW_STEP = 100, 1549, 163, 152, 397, 211
WEAPON_X0, WEAPON_Y, WEAPON_STEP, WEAPON_S = 604, 1964, 211, 162
LEFT = ['head', 'neck', 'shoulder', 'back', 'chest', 'shirt', 'tabard', 'wrist']
RIGHT = ['hands', 'waist', 'legs', 'feet', 'finger1', 'finger2', 'trinket1', 'trinket2']
WEAPONS = ['main_hand', 'off_hand', 'ranged']
MEDALLION = (172, 172, 128)  # centre x, y and the inner radius of the dark socket, source px
TITLE_BAR = (362, 72, 1755, 140)  # the engraved bar's inner area, source px
SEARCH = 22  # px around a predicted edge to search


def _teal(a: np.ndarray) -> np.ndarray:
    r, g, b = a[..., 0], a[..., 1], a[..., 2]
    return (g > r + 18) & (b > r + 18)


def cut_checkerboard(a: np.ndarray) -> np.ndarray:
    """Alpha: 0 on the edge-connected near-grey light region (the baked checkerboard), feathered by a pixel."""
    spread = a.max(axis=2) - a.min(axis=2)
    cand = (spread < CHECKER_SPREAD) & (a.min(axis=2) > CHECKER_MIN)
    lab, _ = ndimage.label(cand)
    edge = set(np.unique(np.concatenate([lab[0], lab[-1], lab[:, 0], lab[:, -1]]))) - {0}
    bg = np.isin(lab, list(edge))
    bg = ndimage.binary_dilation(bg, iterations=1)  # take the anti-aliased fringe with it
    alpha = Image.fromarray(np.where(bg, 0, 255).astype(np.uint8)).filter(ImageFilter.GaussianBlur(.8))
    return np.asarray(alpha)


def _gold(a: np.ndarray) -> np.ndarray:
    """The knotwork: warm and bright, red well over blue."""
    return (a[..., 0] > a[..., 2] + 35) & (a.max(axis=2) > 95)


def inner_box(a: np.ndarray) -> tuple[int, int, int, int]:
    """The knot border's inner gold line (x0, y0, x1, y1), measured outward from the frame's middle along its middle
    row and column: the first gold run on each side."""
    h, w = a.shape[:2]
    cy, cx = int(h * .55), int(w * .5)
    row, col = _gold(a[cy:cy + 1].astype(int))[0], _gold(a[:, cx:cx + 1].astype(int))[:, 0]
    left = max(i for i in range(cx) if row[i]) + 1
    right = min(i for i in range(cx, w) if row[i])
    top = max(i for i in range(cy) if col[i]) + 1
    bottom = min(i for i in range(int(h * .7), h) if col[i])
    return left, top, right, bottom


def clean_centre(a: np.ndarray) -> np.ndarray:
    """The frame's own marble stays in the centre (owner 2026-11-09: no flat cover over it); only the source's fake
    writing and map rings, thin dark strokes, are lifted out of it. A grey closing per channel fills every dark stroke
    thinner than STROKE_PX with the marble around it, a light blur hides the closing's blocks, and the gold knotwork
    (warm and bright, red well over blue) is masked out so it stays sharp."""
    x0, y0, x1, y1 = inner_box(a)
    region = a[y0:y1, x0:x1].astype(float)
    closed = np.stack([ndimage.grey_closing(region[..., c], size=(STROKE_PX, STROKE_PX)) for c in range(3)], axis=-1)
    marble = ndimage.gaussian_filter(closed, sigma=(MARBLE_BLUR, MARBLE_BLUR, 0))
    gold = ndimage.binary_dilation(_gold(region.astype(int)), iterations=3)
    soft = ndimage.gaussian_filter((~gold).astype(float), 1.2)[..., None]
    out = a.copy().astype(float)
    out[y0:y1, x0:x1] = region * (1 - soft) + marble * soft
    return np.clip(out, 0, 255).astype(np.uint8)


def refine(a: np.ndarray, box: tuple[int, int, int, int]) -> tuple[int, int, int, int]:
    """The slot's inner teal edges near the predicted box (x, y, w, h)."""
    x, y, w, h = box
    teal = _teal(a[y - SEARCH:y + h + SEARCH, x - SEARCH:x + w + SEARCH].astype(int))
    rows = np.where(teal.mean(axis=1) > .2)[0]
    cols = np.where(teal.mean(axis=0) > .2)[0]
    if not len(rows) or not len(cols):
        return box
    return (x - SEARCH + cols[0], y - SEARCH + rows[0], cols[-1] - cols[0] + 1, rows[-1] - rows[0] + 1)


HEIGHT_TOLERANCE = 10


def _column(a: np.ndarray, names: list[str], x: int) -> dict[str, tuple[int, int, int, int]]:
    """One column of slots. A refine whose height is off (a glyph crossing the teal edge) takes its top from the mean of
    its neighbours' tops and the column's median height."""
    found = [refine(a, (x, ROW0 + i * ROW_STEP, SLOT_W, SLOT_H)) for i in range(len(names))]
    hs = sorted(b[3] for b in found)
    med = hs[len(hs) // 2]
    ok = [abs(b[3] - med) <= HEIGHT_TOLERANCE for b in found]
    fixed = []
    for i, b in enumerate(found):
        if ok[i]:
            fixed.append(b)
            continue
        above = next((found[j][1] for j in range(i - 1, -1, -1) if ok[j]), None)
        below = next((found[j][1] for j in range(i + 1, len(found)) if ok[j]), None)
        top = (above + below) // 2 if above is not None and below is not None else (above + ROW_STEP if above is not None else below - ROW_STEP)
        fixed.append((b[0], top, b[2], med))
    return dict(zip(names, fixed))


def slots(a: np.ndarray) -> dict[str, tuple[int, int, int, int]]:
    boxes = {**_column(a, LEFT, LEFT_X), **_column(a, RIGHT, RIGHT_X)}
    for i, name in enumerate(WEAPONS):
        boxes[name] = refine(a, (WEAPON_X0 + i * WEAPON_STEP, WEAPON_Y, WEAPON_S, WEAPON_S))
    return boxes


def pct(box: tuple[float, ...], w: int, h: int) -> dict[str, float]:
    x, y, bw, bh = box
    return {'x': round(100 * x / w, 3), 'y': round(100 * y / h, 3), 'w': round(100 * bw / w, 3), 'h': round(100 * bh / h, 3)}


def shift(box: tuple, dx: int, dy: int) -> tuple:
    return (box[0] - dx, box[1] - dy, *box[2:])


def build() -> None:
    src = np.asarray(Image.open(owner_asset(SOURCE)).convert('RGB'))
    measured = slots(src)
    rgb = clean_centre(src)
    alpha = cut_checkerboard(src)
    ys, xs = np.where(alpha > 8)
    x0, y0, x1, y1 = xs.min(), ys.min(), xs.max() + 1, ys.max() + 1  # crop the canvas to the frame's own outline
    rgba = np.dstack([rgb, alpha])[y0:y1, x0:x1]
    h, w = rgba.shape[:2]
    w, h = w - w % 2, h - h % 2  # even, so 1x is exactly half
    rgba = rgba[:h, :w]
    measured = {k: shift(v, x0, y0) for k, v in measured.items()}
    frame = Image.fromarray(rgba, 'RGBA')
    OUT.mkdir(exist_ok=True)
    for scale, im in (('2x', frame), ('1x', frame.resize((w // 2, h // 2), Image.LANCZOS))):
        im.save(OUT / f'frame@{scale}.png', optimize=True)
        im.save(OUT / f'frame@{scale}.webp', quality=88, method=6)
    mx, my, mr = MEDALLION[0] - x0, MEDALLION[1] - y0, MEDALLION[2]
    tx0, ty0, tx1, ty1 = TITLE_BAR[0] - x0, TITLE_BAR[1] - y0, TITLE_BAR[2] - x0, TITLE_BAR[3] - y0
    ix0, iy0, ix1, iy1 = (v - o for v, o in zip(inner_box(src), (x0, y0, x0, y0)))
    cx0, cy0, cx1, cy1 = ix0 + CENTRE_INSET, iy0 + CENTRE_INSET, ix1 - CENTRE_INSET, iy1 - CENTRE_INSET
    spec = {'source': SOURCE, 'size': [w, h], 'slots': {k: pct(v, w, h) for k, v in measured.items()},
            'medallion': pct((mx - mr, my - mr, 2 * mr, 2 * mr), w, h), 'title': pct((tx0, ty0, tx1 - tx0, ty1 - ty0), w, h),
            'centre': pct((cx0, cy0, cx1 - cx0, cy1 - cy0), w, h), 'inner': pct((ix0, iy0, ix1 - ix0, iy1 - iy0), w, h)}
    (OUT / 'slots.json').write_text(json.dumps(spec, indent=1) + '\n')
    for k, v in measured.items():
        print(k, v)


if __name__ == '__main__':
    build()
