/** '#rgb' | '#rrggbb' | 'rgba(r, g, b, a)' to { rgb, alpha }. */
export function parseColor(value) {
  const hex = /^#([0-9a-f]{3}|[0-9a-f]{6})$/i.exec(value);
  if (hex) {
    const h = hex[1].length === 3 ? [...hex[1]].map((c) => c + c).join('') : hex[1];
    return { rgb: parseInt(h, 16), alpha: 1 };
  }
  const rgba = /^rgba?\(\s*(\d+),\s*(\d+),\s*(\d+)(?:,\s*([\d.]+))?\s*\)$/.exec(value);
  if (rgba) {
    const [r, g, b] = [rgba[1], rgba[2], rgba[3]].map(Number);
    return {
      rgb: (r << 16) | (g << 8) | b,
      alpha: rgba[4] === undefined ? 1 : Number(rgba[4]),
    };
  }
  throw new Error(`tokens.json: not a colour: ${value}`);
}

/** '16px' to 16, '0.01em' to 0.01, '120ms' to 120. */
function amount(value, unit) {
  const m = new RegExp(`^(-?[\\d.]+)${unit}$`).exec(value);
  if (!m) throw new Error(`tokens.json: expected a ${unit} value, got ${value}`);
  return Number(m[1]);
}

const nativeDimension = (t, platform, resolve) => {
  const value = t.ext.platformValue?.[platform] ?? (typeof t.ext.phone === 'string' ? t.ext.phone : t.value);
  return amount(resolve(value), 'px');
};

/** A type role as the apps see it: the phone size and line, the native letter spacing. */
function nativeRole(t, resolve, byPath) {
  const v = {
    ...t.value,
    ...(t.ext.phone ?? {}),
    ...(typeof t.ext.native === 'object' ? t.ext.native : {}),
  };
  const familyRef = /^\{([^}]+)\}$/.exec(v.fontFamily)?.[1];
  const family = byPath.get(familyRef);
  const face = family?.ext.faces?.[v.fontWeight];
  if (!face)
    throw new Error(
      `tokens.json: ${t.path.join('.')} names no bundled face (${v.fontFamily} ${v.fontWeight})`,
    );
  return {
    name: t.name,
    face,
    familyName: family.name,
    weight: v.fontWeight,
    size: amount(resolve(v.fontSize), 'px'),
    lineHeight: amount(resolve(v.lineHeight), 'px'),
    tracking: amount(resolve(v.letterSpacing), 'em'),
    scalesWith: t.ext.scalesWith,
    tabular: t.ext.tabular === true,
    description: t.description,
  };
}

/**
 * A token's platform gate: `true`, `false` or a platform name. An object under `native` is the
 * role's native overrides (a type role's letter spacing), not a gate, so the inherited gate stands.
 */
function gate(own, inherited) {
  return own === undefined || typeof own === 'object' ? inherited : own;
}

const isNative = (t, platform) => t.native === true || t.native === platform;
const fmt = (n) => String(n);
const CURVE_ARGS = ['x1', 'y1', 'x2', 'y2'];

