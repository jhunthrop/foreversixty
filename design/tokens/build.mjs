// Android XML (core/designsystem res/values): the colours a resource needs before Compose runs.

const snake = (name) => name.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);

export function renderAndroidXml(model) {
  const colors = model.tokens.filter((t) => t.type === 'color' && t.ext.androidXml === true);
  return [
    `<!-- ${HEADER} -->`,
    `<!-- Run \`${COMMAND}\` after editing tokens.json. A token joins this file with "androidXml": true;`,
    '     app/src/main/res reads these as @color/fs_*, so the window, splash and notification colours',
    '     are the tokens Compose draws with. -->',
    '<resources>',
    ...colors.flatMap((t) => {
      const { rgb, alpha } = parseColor(model.resolve(t.value));
      return [
        ...(t.description ? [`    <!-- ${t.path.join('.')}: ${t.description.replace(/--/g, '-')} -->`] : []),
        `    <color name="fs_${snake(t.name)}">#${alphaHex(alpha)}${hex6(rgb)}</color>`,
      ];
    }),
    '</resources>',
    '',
  ].join('\n');
}

