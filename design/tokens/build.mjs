const hex6 = (rgb) => rgb.toString(16).toUpperCase().padStart(6, '0');
const alphaHex = (alpha) =>
  Math.round(alpha * 255)
    .toString(16)
    .toUpperCase()
    .padStart(2, '0');

/** A gradient token's stops: colour, alpha and position (0 at the start, 1 at the end), in order. */
export function gradientStops(t) {
  return t.value.map(({ color, position }) => {
    if (typeof position !== 'number' || position < 0 || position > 1) {
      throw new Error(`tokens.json: ${t.path.join('.')} has a stop outside 0 to 1: ${position}`);
    }
    return { ...parseColor(color), position };
  });
}

/** Tokens of one top group the platform reads. */
const nativeGroup = (model, top, platform) =>
  model.tokens.filter((t) => t.top === top && isNative(t, platform));

/** One family per font token with faces: its name and [weight, PostScript name] pairs. */
const nativeFaces = (model, platform) =>
  nativeGroup(model, 'font', platform).map((t) => ({
    name: t.name,
    description: t.description,
    faces: Object.entries(t.ext.faces ?? {}).map(([w, postScript]) => ({
      weight: Number(w),
      postScript,
    })),
  }));

const docLines = (description, indent, marker) => (description ? wrapLines(description, indent, marker) : []);

function wrapLines(text, indent, marker) {
  const room = COMMENT_WIDTH - indent.length - marker.length - 1;
  const lines = [];
  let line = '';
  for (const word of text.split(/\s+/)) {
    if (line && line.length + 1 + word.length > room) {
      lines.push(line);
      line = word;
    } else line = line ? `${line} ${word}` : word;
  }
  lines.push(line);
  return lines.map((l) => `${indent}${marker} ${l}`);
}

