const camel = (parts) =>
  parts
    .filter(Boolean)
    .map((p, i) => (i === 0 ? p[0].toLowerCase() + p.slice(1) : p[0].toUpperCase() + p.slice(1)))
    .join('');

/** Every token in document order: path, inherited $type, value, description, extension, the
 *  native identifier and its group's path (for the CSS group comments). */
export function flatten(doc) {
  const tokens = [];
  const groups = new Map();
  const walk = (node, path, inherited) => {
    const ext = node.$extensions?.[EXT] ?? {};
    const type = node.$type ?? inherited.type;
    if ('$value' in node) {
      const [top, ...rest] = path;
      const nameParts = rest.filter((_, i) => !inherited.flattened.includes(i + 1));
      let name = camel(nameParts);
      if (/^\d/.test(name)) name = top + name;
      tokens.push({
        path,
        top,
        type,
        value: node.$value,
        description: node.$description,
        ext,
        native: gate(ext.native, inherited.native),
        name,
        group: path.slice(0, -1).join('.'),
      });
      return;
    }
    groups.set(path.join('.'), node.$description);
    const next = {
      type,
      native: gate(ext.native, inherited.native),
      flattened: ext.flatten ? [...inherited.flattened, path.length - 1] : inherited.flattened,
    };
    for (const [key, child] of Object.entries(node)) {
      if (!key.startsWith('$')) walk(child, [...path, key], next);
    }
  };
  for (const [key, child] of Object.entries(doc)) {
    if (!key.startsWith('$')) walk(child, [key], { type: undefined, native: true, flattened: [] });
  }
  return { tokens, groups };
}

/** Resolves `{a.b.c}` references against the token list, recursively. */
function resolver(tokens) {
  const byPath = new Map(tokens.map((t) => [t.path.join('.'), t]));
  const resolve = (value) => {
    if (typeof value === 'string') {
      const ref = /^\{([^}]+)\}$/.exec(value);
      if (!ref) return value;
      const target = byPath.get(ref[1]);
      if (!target) throw new Error(`tokens.json: unknown reference ${value}`);
      return resolve(target.value);
    }
    if (Array.isArray(value)) return value;
    if (value && typeof value === 'object') {
      return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, resolve(v)]));
    }
    return value;
  };
  return { resolve, byPath };
}

export function loadModel(doc) {
  const { tokens, groups } = flatten(doc);
  const { resolve, byPath } = resolver(tokens);
  const names = new Set();
  for (const t of tokens) {
    if (!(t.top in NATIVE_GROUPS) && t.native !== false && t.top !== 'tracking' && t.top !== 'layout') {
      throw new Error(`tokens.json: ${t.path.join('.')} is in a group no native output knows`);
    }
    const key = `${t.top}.${t.name}`;
    if (t.native !== false && names.has(key)) throw new Error(`tokens.json: two tokens are ${key}`);
    names.add(key);
  }
  return { tokens, groups, resolve, byPath };
}

