/** Every output, keyed by OUTPUTS' keys. */
export function generate(doc = JSON.parse(readFileSync(TOKENS_JSON, 'utf8'))) {
  const model = loadModel(doc);
  return {
    css: renderCss(model),
    companion: renderCompanionCss(model),
    swift: renderSwift(model),
    kotlin: renderKotlin(model),
    go: renderGo(model),
    lua: renderLua(model),
    androidXml: renderAndroidXml(model),
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const [key, text] of Object.entries(generate())) {
    mkdirSync(dirname(OUTPUTS[key]), { recursive: true });
    writeFileSync(OUTPUTS[key], text);
  }
}
