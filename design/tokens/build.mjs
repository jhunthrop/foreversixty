const SWIFT_TEXT_STYLE = new Set([
  'largeTitle',
  'title',
  'title2',
  'title3',
  'headline',
  'subheadline',
  'body',
  'callout',
  'footnote',
  'caption',
  'caption2',
]);

function swiftColor(t) {
  const { rgb, alpha } = parseColor(t.value);
  const opacity = alpha === 1 ? '' : `, opacity: ${alpha}`;
  return `    public static let ${t.name} = Color(tokenHex: 0x${hex6(rgb)}${opacity})`;
}

function swiftEnum(name, lines, description) {
  return [...docLines(description, '', '///'), `public enum FS${name} {`, ...lines, '}', ''];
}

function swiftDocumented(t, line) {
  return [...docLines(t.description, '    ', '///'), line];
}

export function renderSwift(model) {
  const { resolve, byPath } = model;
  const P = 'ios';
  const cg = (t) =>
    swiftDocumented(t, `    public static let ${t.name}: CGFloat = ${fmt(nativeDimension(t, P, resolve))}`);
  const faces = nativeFaces(model, P).flatMap((f) =>
    f.faces.map(
      (face) => `    public static let ${f.name}${WEIGHT_SUFFIX[face.weight]} = "${face.postScript}"`,
    ),
  );
  const roles = nativeGroup(model, 'type', P).map((t) => nativeRole(t, resolve, byPath));
  for (const r of roles) {
    if (!SWIFT_TEXT_STYLE.has(r.scalesWith))
      throw new Error(`tokens.json: type.${r.name} scalesWith ${r.scalesWith}`);
  }
  const shadows = nativeGroup(model, 'elevation', P).map((t) => {
    const v = resolve(t.value);
    const { rgb, alpha } = parseColor(v.color);
    return swiftDocumented(
      t,
      `    public static let ${t.name} = FSShadow(color: Color(tokenHex: 0x${hex6(rgb)}, opacity: ${alpha}), x: ${amount(v.offsetX, 'px')}, y: ${amount(v.offsetY, 'px')}, blur: ${amount(v.blur, 'px')}, spread: ${amount(v.spread ?? '0px', 'px')})`,
    );
  });
  const gradients = nativeGroup(model, 'gradient', P).flatMap((t) =>
    swiftDocumented(t, [
      `    public static let ${t.name}: [Gradient.Stop] = [`,
      ...gradientStops(t).map(
        ({ rgb, alpha, position }) =>
          `        Gradient.Stop(color: Color(tokenHex: 0x${hex6(rgb)}, opacity: ${fmt(alpha)}), location: ${fmt(position)}),`,
      ),
      '    ]',
    ].join('\n')),
  );
  const motion = nativeGroup(model, 'motion', P).flatMap((t) =>
    t.type === 'cubicBezier'
      ? swiftDocumented(
          t,
          `    public static let ${t.name} = FSCurve(${t.value.map((n, i) => `${CURVE_ARGS[i]}: ${fmt(n)}`).join(', ')})`,
        )
      : swiftDocumented(
          t,
          `    /// ${t.value}\n    public static let ${t.name}: TimeInterval = ${fmt(amount(t.value, 'ms') / 1000)}`,
        ),
  );
  return [
    `// ${HEADER}`,
    '// The site is dark only, so these are the one theme. The faces are the files in apps/shared/fonts that',
    '// project.yml lists under UIAppFonts; FSFont names them by PostScript name. Public: DesignSystem',
    '// reads them from this module.',
    '',
    'import SwiftUI',
    '',
    'public extension Color {',
    '    /// 0xRRGGBB plus an optional opacity.',
    '    init(tokenHex: UInt32, opacity: Double = 1) {',
    '        self.init(',
    '            .sRGB,',
    '            red: Double((tokenHex >> 16) & 0xFF) / 255,',
    '            green: Double((tokenHex >> 8) & 0xFF) / 255,',
    '            blue: Double(tokenHex & 0xFF) / 255,',
    '            opacity: opacity',
    '        )',
    '    }',
    '}',
    '',
    '/// A type role: its face, size and line box in points, letter spacing in em (multiply by the size',
    '/// for SwiftUI `tracking`), the Dynamic Type style it scales with, and whether its digits are tabular.',
    'public struct FSTextRole: Sendable {',
    '    public let face: String',
    '    public let size: CGFloat',
    '    public let lineHeight: CGFloat',
    '    public let tracking: CGFloat',
    '    public let scalesWith: Font.TextStyle',
    '    public let tabular: Bool',
    '}',
    '',
    '/// A shadow: colour, offset and blur in points.',
    'public struct FSShadow: Sendable {',
    '    public let color: Color',
    '    public let x: CGFloat',
    '    public let y: CGFloat',
    '    public let blur: CGFloat',
    '    public let spread: CGFloat',
    '}',
    '',
    '/// A cubic Bézier easing curve.',
    'public struct FSCurve: Sendable {',
    '    public let x1: Double',
    '    public let y1: Double',
    '    public let x2: Double',
    '    public let y2: Double',
    '}',
    '',
    ...swiftEnum(
      'Color',
      nativeGroup(model, 'color', P).flatMap((t) => swiftDocumented(t, swiftColor(t))),
    ),
    ...swiftEnum('Font', faces),
    ...swiftEnum(
      'Type',
      roles.flatMap((r) =>
        swiftDocumented(
          r,
          `    public static let ${r.name} = FSTextRole(face: FSFont.${r.familyName}${WEIGHT_SUFFIX[r.weight]}, size: ${fmt(r.size)}, lineHeight: ${fmt(r.lineHeight)}, tracking: ${fmt(r.tracking)}, scalesWith: .${r.scalesWith}, tabular: ${r.tabular})`,
        ),
      ),
    ),
    ...swiftEnum('TextSize', nativeGroup(model, 'textLegacy', P).flatMap(cg), model.groups.get('textLegacy')),
    ...swiftEnum('Space', nativeGroup(model, 'space', P).flatMap(cg)),
    ...swiftEnum('Size', nativeGroup(model, 'size', P).flatMap(cg)),
    ...swiftEnum('Target', nativeGroup(model, 'target', P).flatMap(cg), model.groups.get('target')),
    ...swiftEnum('Radius', nativeGroup(model, 'radius', P).flatMap(cg)),
    ...swiftEnum('Stroke', nativeGroup(model, 'stroke', P).flatMap(cg)),
    ...swiftEnum('Elevation', shadows.flat()),
    ...swiftEnum('Gradient', gradients, model.groups.get('gradient')),
    ...swiftEnum('Motion', motion, model.groups.get('motion')),
  ]
    .join('\n')
    .replace(/\n+$/, '\n');
}

