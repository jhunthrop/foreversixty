function wrapComment(text, indent) {
  const words = text.split(/\s+/);
  const lines = [];
  let line = '';
  const room = COMMENT_WIDTH - indent.length - 3;
  for (const word of words) {
    if (line && line.length + 1 + word.length > room) {
      lines.push(line);
      line = word;
    } else line = line ? `${line} ${word}` : word;
  }
  lines.push(line);
  return lines.map((l, i) => `${indent}${i === 0 ? '/* ' : '   '}${l}${i === lines.length - 1 ? ' */' : ''}`);
}

const cssDim = (v) => (/^0(px)?$/.test(v) ? '0' : v);

function cssValue(t, value, resolve) {
  const v = resolve(value);
  switch (t.type) {
    case 'fontFamily':
      return v.map((f) => (GENERIC_FAMILIES.has(f) ? f : `'${f}'`)).join(', ');
    case 'shadow': {
      const parts = [cssDim(v.offsetX), cssDim(v.offsetY), cssDim(v.blur)];
      if (v.spread && cssDim(v.spread) !== '0') parts.push(v.spread);
      return `${v.inset ? 'inset ' : ''}${parts.join(' ')} ${v.color}`;
    }
    default:
      return v;
  }
}

/** The value the web takes: `platformValue.web` where the site leads a change the apps have not
 *  adopted yet (round 5's palette, type and radii), else the shared value. A typography override
 *  merges over the shared role and may carry its own `phone`. */
export function webValue(t) {
  const web = t.ext.platformValue?.web;
  if (web === undefined) return { value: t.value, phone: t.ext.phone ?? {} };
  if (t.type !== 'typography') return { value: web, phone: t.ext.phone ?? {} };
  const { phone, ...rest } = web;
  return { value: { ...t.value, ...rest }, phone: phone ?? t.ext.phone ?? {} };
}

/** The custom properties a token defines: [name, value] pairs, aliases after. */
function cssDeclarations(t, resolve) {
  const css = t.ext.css;
  if (!css) return [];
  const { value, phone } = webValue(t);
  if (t.type === 'typography') {
    return [
      [css.fontSize, value.fontSize],
      [css.lineHeight, value.lineHeight],
      [css.phoneFontSize, phone.fontSize],
      [css.phoneLineHeight, phone.lineHeight],
    ]
      .filter(([name]) => name)
      .map(([name, v]) => [name, resolve(v)]);
  }
  return [[css, cssValue(t, value, resolve)], ...(t.ext.cssAliases ?? []).map((a) => [a, `var(${css})`])];
}

/** The declarations of every token the web carries, with their group and token comments. */
function cssBody({ tokens, groups, resolve }) {
  const out = [];
  let group = null;
  for (const t of tokens) {
    const decls = cssDeclarations(t, resolve);
    if (!decls.length) continue;
    if (t.group !== group) {
      if (group !== null) out.push('');
      group = t.group;
      const description = groups.get(t.group);
      if (description) out.push(...wrapComment(description, '  '));
    }
    if (t.description) out.push(...wrapComment(t.description, '  '));
    for (const [name, value] of decls) out.push(`  ${name}: ${value};`);
  }
  return out;
}

export function renderCss(model) {
  const { tokens, resolve, byPath } = model;
  const out = [
    `/* ${HEADER} */`,
    ...wrapComment(
      '`static`: the report reads class and outcome colours through var() in inline styles and getComputedStyle, which Tailwind cannot see, and without `static` it drops every theme variable no utility class references.',
      '',
    ),
    '@theme static {',
    ...cssBody(model),
  ];
  out.push('}', '');
  const wide = tokens.filter((t) => t.ext.wide && t.ext.css);
  const breakpoint = resolve(byPath.get('layout.breakpointWide').value);
  out.push(
    ...wrapComment(
      `The wide frame (spec 3.2, owner decisions 2026-11-05 and 2026-11-10): from ${breakpoint} the one frame grows, with the wider gutter, gaps and rails, on every page alike ("consistent width for every experience").`,
      '',
    ),
    `@media (min-width: ${breakpoint}) {`,
    '  :root {',
    ...wide.map((t) => `    ${t.ext.css}: ${resolve(t.ext.wide)};`),
    '  }',
    '}',
    '',
  );
  return out.join('\n');
}

/** The desktop companion's window (companion/ui, embedded in the Go binary) has no Tailwind: the
 *  same custom properties, the web's values, on :root. It is one fixed window, so no wide block. */
export function renderCompanionCss(model) {
  return [
    `/* ${HEADER} */`,
    ...wrapComment(
      'The companion window reads these exactly as the site does (var(--color-raised), var(--radius-plate) ...); companion/ui/styles.css composes them and declares no colour of its own.',
      '',
    ),
    ':root {',
    ...cssBody(model),
    '}',
    '',
  ].join('\n');
}

