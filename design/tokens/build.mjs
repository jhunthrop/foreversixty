function kotlinObject(name, lines, description) {
  return [...docLines(description, '', '//'), `object Fs${name} {`, ...lines, '}', ''];
}

const kotlinDocumented = (t, line) => [...docLines(t.description, '    ', '//'), line];
const kFloat = (n) => `${fmt(n)}f`;
const fontResource = (postScript) => postScript.toLowerCase().replace(/-/g, '_');

export function renderKotlin(model) {
  const { resolve, byPath } = model;
  const P = 'android';
  const dp = (t) => kotlinDocumented(t, `    val ${t.name} = ${fmt(nativeDimension(t, P, resolve))}.dp`);
  const sp = (t) => kotlinDocumented(t, `    val ${t.name} = ${fmt(nativeDimension(t, P, resolve))}.sp`);
  const color = (t) => {
    const { rgb, alpha } = parseColor(t.value);
    return kotlinDocumented(t, `    val ${t.name} = Color(0x${alphaHex(alpha)}${hex6(rgb)})`);
  };
  const families = nativeFaces(model, P).map(
    (f) =>
      `    val ${f.name} = FontFamily(${f.faces.map((face) => `Font(R.font.${fontResource(face.postScript)}, FontWeight.${KOTLIN_WEIGHT[face.weight]})`).join(', ')})`,
  );
  const roles = nativeGroup(model, 'type', P).flatMap((t) => {
    const r = nativeRole(t, resolve, byPath);
    const args = [
      `fontFamily = FsFont.${r.familyName}`,
      `fontWeight = FontWeight.${KOTLIN_WEIGHT[r.weight]}`,
      `fontSize = ${fmt(r.size)}.sp`,
      `lineHeight = ${fmt(r.lineHeight)}.sp`,
      `letterSpacing = ${fmt(r.tracking)}.em`,
      'lineHeightStyle = CenteredLines',
      ...(r.tabular ? ['fontFeatureSettings = "tnum"'] : []),
    ];
    return kotlinDocumented(r, `    val ${r.name} = TextStyle(${args.join(', ')})`);
  });
  const shapes = nativeGroup(model, 'radius', P).flatMap((t) =>
    kotlinDocumented(t, `    val ${t.name} = RoundedCornerShape(${fmt(nativeDimension(t, P, resolve))}.dp)`),
  );
  const shadows = nativeGroup(model, 'elevation', P).flatMap((t) => {
    const v = resolve(t.value);
    const { rgb, alpha } = parseColor(v.color);
    return kotlinDocumented(
      t,
      `    val ${t.name} = FsShadow(Color(0x${alphaHex(alpha)}${hex6(rgb)}), ${amount(v.offsetX, 'px')}.dp, ${amount(v.offsetY, 'px')}.dp, ${amount(v.blur, 'px')}.dp, ${amount(v.spread ?? '0px', 'px')}.dp)`,
    );
  });
  const gradients = nativeGroup(model, 'gradient', P).flatMap((t) =>
    kotlinDocumented(t, [
      `    val ${t.name}: List<Pair<Float, Color>> = listOf(`,
      ...gradientStops(t).map(
        ({ rgb, alpha, position }) => `        ${kFloat(position)} to Color(0x${alphaHex(alpha)}${hex6(rgb)}),`,
      ),
      '    )',
    ].join('\n')),
  );
  const motion = nativeGroup(model, 'motion', P).flatMap((t) =>
    t.type === 'cubicBezier'
      ? kotlinDocumented(t, `    val ${t.name} = CubicBezierEasing(${t.value.map(kFloat).join(', ')})`)
      : kotlinDocumented(t, `    /** Milliseconds. */\n    val ${t.name} = ${amount(t.value, 'ms')}`),
  );
  return [
    `// ${HEADER}`,
    '// The site is dark only, so these are the one theme. The faces are the files in apps/shared/fonts,',
    '// copied to res/font with lowercase underscore names by the forever.shared-fonts plugin.',
    '@file:Suppress("MagicNumber")',
    '',
    `package ${KOTLIN_PACKAGE}`,
    '',
    'import androidx.compose.animation.core.CubicBezierEasing',
    'import androidx.compose.foundation.shape.RoundedCornerShape',
    'import androidx.compose.ui.graphics.Color',
    'import androidx.compose.ui.text.TextStyle',
    'import androidx.compose.ui.text.font.Font',
    'import androidx.compose.ui.text.font.FontFamily',
    'import androidx.compose.ui.text.font.FontWeight',
    'import androidx.compose.ui.text.style.LineHeightStyle',
    'import androidx.compose.ui.unit.Dp',
    'import androidx.compose.ui.unit.dp',
    'import androidx.compose.ui.unit.em',
    'import androidx.compose.ui.unit.sp',
    '',
    '/** A shadow: colour, offset, blur and spread. */',
    'data class FsShadow(val color: Color, val x: Dp, val y: Dp, val blur: Dp, val spread: Dp)',
    '',
    '/** Every role centres its glyphs in the line box and keeps the full line height (spec 3.2). */',
    'private val CenteredLines = LineHeightStyle(LineHeightStyle.Alignment.Center, LineHeightStyle.Trim.None)',
    '',
    ...kotlinObject('Color', nativeGroup(model, 'color', P).flatMap(color)),
    ...kotlinObject('Font', families),
    ...kotlinObject('Type', roles),
    ...kotlinObject(
      'TextSize',
      nativeGroup(model, 'textLegacy', P).flatMap(sp),
      model.groups.get('textLegacy'),
    ),
    ...kotlinObject('Space', nativeGroup(model, 'space', P).flatMap(dp)),
    ...kotlinObject('Size', nativeGroup(model, 'size', P).flatMap(dp)),
    ...kotlinObject('Target', nativeGroup(model, 'target', P).flatMap(dp), model.groups.get('target')),
    ...kotlinObject('Radius', nativeGroup(model, 'radius', P).flatMap(dp)),
    ...kotlinObject('Shape', shapes),
    ...kotlinObject('Stroke', nativeGroup(model, 'stroke', P).flatMap(dp)),
    ...kotlinObject('Elevation', shadows),
    ...kotlinObject('Gradient', gradients, model.groups.get('gradient')),
    ...kotlinObject('Motion', motion, model.groups.get('motion')),
  ]
    .join('\n')
    .replace(/\n+$/, '\n');
}


