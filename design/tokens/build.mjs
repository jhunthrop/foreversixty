// Lua (addon/ForeverSixty/Tokens.lua): the web's values, since the addon draws what the site shows.

/** A token that names one platform (native: 'lua', 'androidXml') lives only in that output. */
const isPlatformOnly = (t) => typeof t.native === 'string';

/** The groups the addon reads, nested by token path (Tokens.color.base.bg, Tokens.space[4]). */
const LUA_GROUPS = ['color', 'font', 'type', 'space', 'size', 'radius', 'stroke'];

const luaKey = (key) => {
  if (/^[A-Za-z_]\w*$/.test(key)) return key;
  if (/^\d+$/.test(key)) return `[${key}]`;
  return `[${JSON.stringify(key)}]`;
};

/** The font a role reads, as its key under Tokens.font (`{font.title}` to "title"). */
function luaFontKey(value) {
  const ref = /^\{font\.([^}]+)\}$/.exec(value);
  if (!ref) throw new Error(`tokens.json: a type role's fontFamily must reference a font token, got ${value}`);
  return ref[1];
}

/** A font the addon ships: each weight's file in the addon's media/fonts, and the client face that
 *  stands in where the client refuses it. Fonts without a `lua` extension are not in the addon. */
function luaFont(t) {
  const pad = '\t'.repeat(t.path.length);
  const faces = Object.entries(t.ext.faces ?? {}).map(
    ([weight, postScript]) => `${pad}\t\t[${weight}] = ${JSON.stringify(`${ADDON_FONT_PATH}${postScript}.ttf`)},`,
  );
  return [
    '{',
    `${pad}\tfaces = {`,
    ...faces,
    `${pad}\t},`,
    `${pad}\tfallback = ${JSON.stringify(t.ext.lua.fallback)},`,
    `${pad}}`,
  ].join('\n');
}

/** A type role as the web sets it at 768 px and up: face key, weight, size and line in UI units. */
function luaRole(t, resolve) {
  const { value } = webValue(t);
  const px = (v) => fmt(amount(resolve(v), 'px'));
  return `{ font = "${luaFontKey(value.fontFamily)}", weight = ${value.fontWeight}, size = ${px(value.fontSize)}, line = ${px(value.lineHeight)} }`;
}

/** One token's Lua value, or null when the addon has no use for it. */
function luaValue(t, resolve) {
  const { value } = webValue(t);
  switch (t.type) {
    case 'color':
      return JSON.stringify(hex6(parseColor(resolve(value)).rgb).toLowerCase());
    case 'fontFamily':
      return t.ext.lua ? luaFont(t) : null;
    case 'typography':
      return luaRole(t, resolve);
    default:
      return fmt(amount(resolve(value), 'px'));
  }
}

/** Nests [path, line] entries into Lua table lines, keys in document order. */
function luaTable(entries, indent) {
  const tree = new Map();
  for (const { path, value, description } of entries) {
    let node = tree;
    for (const key of path.slice(0, -1)) {
      if (!node.has(key)) node.set(key, new Map());
      node = node.get(key);
    }
    node.set(path[path.length - 1], { value, description });
  }
  const render = (node, pad) =>
    [...node].flatMap(([key, child]) =>
      child instanceof Map
        ? [`${pad}${luaKey(key)} = {`, ...render(child, `${pad}\t`), `${pad}},`]
        : [...docLines(child.description, pad, '---'), `${pad}${luaKey(key)} = ${child.value},`],
    );
  return render(tree, indent);
}

export function renderLua(model) {
  const { resolve } = model;
  const tokens = model.tokens.filter(
    (t) => LUA_GROUPS.includes(t.top) && (!isPlatformOnly(t) || t.native === 'lua'),
  );
  const values = tokens
    .map((t) => ({ path: t.path, value: luaValue(t, resolve), description: t.description }))
    .filter((e) => e.value !== null);
  const alphas = tokens
    .filter((t) => t.type === 'color' && parseColor(resolve(webValue(t).value)).alpha < 1)
    .map((t) => ({
      path: t.path.slice(1),
      value: fmt(parseColor(resolve(webValue(t).value)).alpha),
    }));
  return [
    `-- ${HEADER}`,
    `-- Run \`${COMMAND}\` after editing tokens.json.`,
    '-- The one palette, type and measure the addon draws with: Theme.lua reads these and nothing else',
    '-- names a colour. Colours are six lowercase hex digits (the web value); a colour that is not',
    '-- opaque on the web has its alpha under Tokens.alpha at the same path. Faces are the files in',
    '-- media/fonts (copies of apps/shared/fonts), with the client face that stands in for each.',
    'local _, ns = ...',
    'ns = type(ns) == "table" and ns or {}',
    '',
    'local Tokens = {',
    ...luaTable(values, '\t'),
    '\talpha = {',
    ...luaTable(alphas, '\t\t'),
    '\t},',
    '}',
    '',
    'ns.Tokens = Tokens',
    'return Tokens',
    '',
  ].join('\n');
}

