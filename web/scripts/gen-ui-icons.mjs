// web/scripts/gen-ui-icons.mjs
// Writes src/lib/ui/ui-icons.ts, the site's one icon source, from design/assets/icons/ui:
// - *.svg is the owner's custom set: one filled path on a square viewBox (traced by that
//   folder's trace.py), drawn even-odd in currentColor.
// - line/*.svg is the utility family the custom set does not cover (chevrons, close, check,
//   menu, the BiS source kinds ...): one 24 px grid, a 2 px round stroke, or a solid shape
//   where the root says fill="currentColor".
// The rule between them: the custom set marks a place or an object (doors, panel rows, account
// tiles, settings rows), drawn at 20 px and up; the line family marks a control or a state.
// Each icon is its own module under src/lib/ui/icons/, re-exported by ui-icons.ts, so the
// bundler splits icons by the islands that use them and an island carries only its own (one
// module of every icon put the union of all islands' icons in one shared chunk). UI_ICONS is the
// name lookup for build-time callers (Astro, the contact sheet, tests). ui/Icon.svelte and
// ui/Icon.astro draw an entry; src/lib/ui/ui-icons.test.ts fails on a stale output.
// The desktop companion's window (companion/ui) draws from the same source: COMPANION_ICONS are
// written to companion/ui/icons.js, with the lead panel's corner flourish
// (design/assets/ornaments/corner-filigree.svg), as a plain script its page loads.
// Run: node scripts/gen-ui-icons.mjs
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const WEB = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const ICON_DIR = path.resolve(WEB, '../design/assets/icons/ui');
export const LINE_DIR = path.join(ICON_DIR, 'line');
export const OUT = path.join(WEB, 'src/lib/ui/ui-icons.ts');
export const MODULE_DIR = path.join(WEB, 'src/lib/ui/icons');
export const COMPANION_OUT = path.resolve(WEB, '../companion/ui/icons.js');
const CORNER_SVG = path.resolve(WEB, '../design/assets/ornaments/corner-filigree.svg');

/** The glyphs the companion window draws: its four page tabs (upload Status, logs Reports,
 *  account Device, setup Settings), the check of a done action and a select's chevron. Its other
 *  actions are words alone (ai-slop-reviewer, batch G). */
export const COMPANION_ICONS = ['account', 'check', 'chevron-down', 'logs', 'setup', 'upload'];

/** The line family's one grid. */
const LINE_BOX = 24;
const LINE_ELEMENTS = new Set(['path', 'circle']);

function svgFiles(dir) {
  return readdirSync(dir)
    .filter((file) => file.endsWith('.svg'))
    .sort();
}

function parseCustom(file) {
  const svg = readFileSync(path.join(ICON_DIR, file), 'utf8');
  const viewBox = /viewBox="0 0 (\d+) (\d+)"/.exec(svg);
  const paths = [...svg.matchAll(/<path\b[^>]*\sd="([^"]+)"/g)];
  if (viewBox === null || viewBox[1] !== viewBox[2]) throw new Error(`${file}: needs a square viewBox`);
  if (paths.length !== 1) throw new Error(`${file}: needs exactly one path, found ${paths.length}`);
  return {
    name: file.slice(0, -4),
    box: Number(viewBox[1]),
    kind: 'fill',
    body: `<path fill-rule="evenodd" d="${paths[0][1]}"/>`,
  };
}

function parseLine(file) {
  const svg = readFileSync(path.join(LINE_DIR, file), 'utf8');
  const root = /^<svg\b([^>]*)>([\s\S]*)<\/svg>\s*$/.exec(svg);
  if (root === null) throw new Error(`line/${file}: needs one <svg> root`);
  const [, attrs, body] = root;
  if (!attrs.includes(`viewBox="0 0 ${LINE_BOX} ${LINE_BOX}"`))
    throw new Error(`line/${file}: needs the 24 px grid`);
  const filled = attrs.includes('fill="currentColor"');
  if (!filled && !attrs.includes('stroke-width="2"')) throw new Error(`line/${file}: needs the 2 px stroke`);
  for (const [, tag] of body.matchAll(/<(\w+)/g)) {
    if (!LINE_ELEMENTS.has(tag)) throw new Error(`line/${file}: <${tag}> is not a path or circle`);
  }
  if (/stroke|fill|style|on\w+=/.test(body)) throw new Error(`line/${file}: paint lives on the root only`);
  return { name: file.slice(0, -4), box: LINE_BOX, kind: filled ? 'fill' : 'line', body: body.trim() };
}

/** `chevron-down` -> `ICON_CHEVRON_DOWN`. */
const exportName = (name) => `ICON_${name.toUpperCase().replace(/-/g, '_')}`;

function iconModule(icon) {
  const shape = `{ name: '${icon.name}', box: ${icon.box}, kind: '${icon.kind}', body: '${icon.body}' }`;
  return `// web/src/lib/ui/icons/${icon.name}.ts
// GENERATED by scripts/gen-ui-icons.mjs from design/assets/icons/ui. Do not edit.
import type { UiIconShape } from '../ui-icons';

export const ${exportName(icon.name)}: UiIconShape = ${shape};
`;
}

function readIcons() {
  const custom = svgFiles(ICON_DIR).map(parseCustom);
  const line = svgFiles(LINE_DIR).map(parseLine);
  const clash = custom.find((icon) => line.some((other) => other.name === icon.name));
  if (clash !== undefined) throw new Error(`${clash.name}: drawn in both families; one meaning, one glyph`);
  return { custom, line, all: [...custom, ...line].sort((a, b) => a.name.localeCompare(b.name)) };
}

function parseCorner() {
  const svg = readFileSync(CORNER_SVG, 'utf8');
  const viewBox = /viewBox="0 0 (\d+) (\d+)"/.exec(svg);
  const paths = [...svg.matchAll(/<path\b[^>]*\sd="([^"]+)"/g)];
  if (viewBox === null || viewBox[1] !== viewBox[2] || paths.length !== 1)
    throw new Error('corner-filigree.svg: needs one path on a square viewBox');
  return { box: Number(viewBox[1]), body: `<path fill-rule="evenodd" d="${paths[0][1]}"/>` };
}

function companionScript(all) {
  const byName = new Map(all.map((icon) => [icon.name, icon]));
  const icons = COMPANION_ICONS.map((name) => {
    const icon = byName.get(name);
    if (icon === undefined)
      throw new Error(`COMPANION_ICONS names ${name}, which design/assets/icons/ui lacks`);
    return `  '${icon.name}': { box: ${icon.box}, kind: '${icon.kind}', body: '${icon.body}' },`;
  });
  const corner = parseCorner();
  return `// companion/ui/icons.js
// GENERATED by web/scripts/gen-ui-icons.mjs from design/assets/icons/ui. Do not edit.
// The site's icon set, the glyphs the companion window draws (COMPANION_ICONS there), plus the
// lead panel's corner flourish. app.js icon() draws an entry in currentColor: a fill kind as one
// even-odd shape, a line kind as a 2 px round stroke on the 24 px grid.
'use strict';

const UI_ICONS = {
${icons.join('\n')}
};

const FRAME_CORNER = { box: ${corner.box}, body: '${corner.body}' };

if (typeof module !== 'undefined') module.exports = { UI_ICONS, FRAME_CORNER };
`;
}

/** Every generated file: `ui-icons.ts` and one module per icon, keyed by absolute path. */
export function renderUiIcons() {
  const { custom, line, all } = readIcons();
  const index = `// web/src/lib/ui/ui-icons.ts
// GENERATED by scripts/gen-ui-icons.mjs from design/assets/icons/ui. Do not edit.
// The site's one icon source: the owner's custom set (filled, even-odd, on its own square grid)
// and the line family (24 px grid, 2 px round stroke) for the utility glyphs the custom set does
// not cover. Drawn in currentColor by ui/Icon.svelte and ui/Icon.astro, never inline. Each icon
// lives in its own module (./icons/), so an island bundles only the icons it imports.

export interface UiIconShape {
  /** The source file's name: the drawn svg's data-icon. */
  readonly name: string;
  /** The square viewBox's side. */
  readonly box: number;
  /** A solid shape in currentColor, or a 2 px currentColor line. */
  readonly kind: 'fill' | 'line';
  /** The svg's inner markup: paths and circles only, unpainted. */
  readonly body: string;
}

// Custom set: ${custom.map((icon) => icon.name).join(', ')}.
// Line family: ${line.map((icon) => icon.name).join(', ')}.

${all.map((icon) => `import { ${exportName(icon.name)} } from './icons/${icon.name}';`).join('\n')}

export {
${all.map((icon) => `  ${exportName(icon.name)},`).join('\n')}
};

/** Every icon by name, for build-time callers; an island imports the one export it draws. */
export const UI_ICONS = {
${all.map((icon) => `  '${icon.name}': ${exportName(icon.name)},`).join('\n')}
} as const satisfies Record<string, UiIconShape>;

export type UiIconName = keyof typeof UI_ICONS;
`;
  return new Map([
    [OUT, index],
    [COMPANION_OUT, companionScript(all)],
    ...all.map((icon) => [path.join(MODULE_DIR, `${icon.name}.ts`), iconModule(icon)]),
  ]);
}

// ---------------------------------------------------------------------------------------------
// The apps' vectors (lane M0): the owner's traced tab icons (design/assets/icons/nav, spec
// "Tab-bar icons"; the unified set above has no gear or activity glyph; Guild is its door) and the lead
// panel's corner ornament (design/assets/ornaments/corner-filigree.svg, ui/FrameCorners.svelte),
// as an iOS template image set (SVG, vector kept) in apps/shared/brand/ios/Brand.xcassets and an
// Android VectorDrawable in the design system's res/drawable. Never hand-copied paths: each is the
// source's one even-odd path, with the stroke design/assets/icons/nav/thicken.json bakes in.

const ASSETS = path.resolve(WEB, '../design/assets');
const APPS = path.resolve(WEB, '../apps');
export const NATIVE_IOS_DIR = path.join(APPS, 'shared/brand/ios/Brand.xcassets/Vectors');
export const NATIVE_ANDROID_DIR = path.join(APPS, 'android/core/designsystem/src/main/res/drawable');
const THICKEN = JSON.parse(readFileSync(path.join(ASSETS, 'icons/nav/thicken.json'), 'utf8'));
/** Each native vector: its asset name, its source and its drawn size in pt / dp. */
/** The tab icons' sources: the owner's traced nav set, and for Guild the site's own Guild door
 *  (icons/ui/guild.svg, the glyph the header's Guild draws; spec 2026-11-10-guild-tab.md section 1). */
const TAB_SOURCES = {
  home: 'icons/nav/home.svg',
  guild: 'icons/ui/guild.svg',
  gear: 'icons/nav/gear.svg',
  activity: 'icons/nav/activity.svg',
};
const NATIVE_VECTORS = [
  ...Object.entries(TAB_SOURCES).map(([name, source]) => ({
    name: `tab-${name}`,
    source,
    size: 24,
    stroke: THICKEN[name] ?? 0,
  })),
  // The filigree is drawn exactly (owner: faithful game art), so its one long path keeps every
  // point; at 44 dp, drawn four times per frame, it is cheap, and lint's VectorPath is waived on it.
  {
    name: 'frame-corner',
    source: 'ornaments/corner-filigree.svg',
    size: 44,
    stroke: 0,
    lintIgnore: 'VectorPath',
  },
];
const NATIVE_HEADER = 'GENERATED by web/scripts/gen-ui-icons.mjs from design/assets. Do not edit.';

function parseNative(vector) {
  const svg = readFileSync(path.join(ASSETS, vector.source), 'utf8');
  const viewBox = /viewBox="0 0 (\d+) (\d+)"/.exec(svg);
  const paths = [...svg.matchAll(/<path\b[^>]*\sd="([^"]+)"/g)];
  if (viewBox === null || viewBox[1] !== viewBox[2])
    throw new Error(`${vector.source}: needs a square viewBox`);
  if (paths.length !== 1) throw new Error(`${vector.source}: needs exactly one path, found ${paths.length}`);
  return { ...vector, box: Number(viewBox[1]), d: paths[0][1] };
}

function iosSvg(icon) {
  const stroke = icon.stroke ? ` stroke="#000" stroke-width="${icon.stroke}" stroke-linejoin="round"` : '';
  return `<!-- ${NATIVE_HEADER} -->
<svg xmlns="http://www.w3.org/2000/svg" width="${icon.size}" height="${icon.size}" viewBox="0 0 ${icon.box} ${icon.box}"><path fill="#000" fill-rule="evenodd"${stroke} d="${icon.d}"/></svg>
`;
}

// A template image: the app tints it (the tab bar's gold or muted white, the corner's cream).
const iosContents = (icon) =>
  `${JSON.stringify(
    {
      images: [{ filename: `${icon.name}.svg`, idiom: 'universal' }],
      info: { author: 'xcode', version: 1 },
      properties: { 'preserves-vector-representation': true, 'template-rendering-intent': 'template' },
    },
    null,
    2,
  )}\n`;

function androidVector(icon) {
  const lintIgnore = icon.lintIgnore
    ? `
    xmlns:tools="http://schemas.android.com/tools"
    tools:ignore="${icon.lintIgnore}"`
    : '';
  const stroke = icon.stroke
    ? `
        android:strokeColor="#FFFFFFFF"
        android:strokeWidth="${icon.stroke}"
        android:strokeLineJoin="round"`
    : '';
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- ${NATIVE_HEADER} -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"${lintIgnore}
    android:width="${icon.size}dp"
    android:height="${icon.size}dp"
    android:viewportWidth="${icon.box}"
    android:viewportHeight="${icon.box}">
    <path
        android:fillColor="#FFFFFFFF"
        android:fillType="evenOdd"${stroke}
        android:pathData="${icon.d}" />
</vector>
`;
}

/** Every native vector file, keyed by absolute path. */
export function renderNativeIcons() {
  const out = new Map([
    [
      path.join(NATIVE_IOS_DIR, 'Contents.json'),
      `${JSON.stringify({ info: { author: 'xcode', version: 1 } }, null, 2)}\n`,
    ],
  ]);
  for (const icon of NATIVE_VECTORS.map(parseNative)) {
    const set = path.join(NATIVE_IOS_DIR, `${icon.name}.imageset`);
    out.set(path.join(set, `${icon.name}.svg`), iosSvg(icon));
    out.set(path.join(set, 'Contents.json'), iosContents(icon));
    out.set(path.join(NATIVE_ANDROID_DIR, `ic_${icon.name.replace(/-/g, '_')}.xml`), androidVector(icon));
  }
  return out;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  rmSync(MODULE_DIR, { recursive: true, force: true });
  mkdirSync(MODULE_DIR, { recursive: true });
  const files = renderUiIcons();
  for (const [file, text] of files) writeFileSync(file, text);
  console.log(
    `wrote ${path.relative(WEB, OUT)}, ${path.relative(WEB, COMPANION_OUT)} and ${files.size - 2} icon modules`,
  );
  rmSync(NATIVE_IOS_DIR, { recursive: true, force: true });
  const native = renderNativeIcons();
  for (const [file, text] of native) {
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, text);
  }
  console.log(`wrote ${native.size} native vector files`);
}
