// web/scripts/gen-ui-icons.mjs
// Writes src/lib/ui/ui-icons.ts from the owner's custom icon set, design/assets/icons/ui/*.svg
// (single filled path, square viewBox; traced by that folder's trace.py). The SVG files are the
// one source; ui/Icon.svelte draws an entry, and src/lib/ui/ui-icons.test.ts fails on a stale
// output. Run: node scripts/gen-ui-icons.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const WEB = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const ICON_DIR = path.resolve(WEB, '../design/assets/icons/ui');
export const OUT = path.join(WEB, 'src/lib/ui/ui-icons.ts');

function parseIcon(file) {
  const svg = readFileSync(path.join(ICON_DIR, file), 'utf8');
  const viewBox = /viewBox="0 0 (\d+) (\d+)"/.exec(svg);
  const paths = [...svg.matchAll(/<path\b[^>]*\sd="([^"]+)"/g)];
  if (viewBox === null || viewBox[1] !== viewBox[2]) throw new Error(`${file}: needs a square viewBox`);
  if (paths.length !== 1) throw new Error(`${file}: needs exactly one path, found ${paths.length}`);
  return { name: file.slice(0, -4), size: Number(viewBox[1]), d: paths[0][1] };
}

export function renderUiIcons() {
  const icons = readdirSync(ICON_DIR)
    .filter((file) => file.endsWith('.svg'))
    .sort()
    .map(parseIcon);
  const entries = icons.map((icon) => `  '${icon.name}': { size: ${icon.size}, d: '${icon.d}' },`).join('\n');
  return `// web/src/lib/ui/ui-icons.ts
// GENERATED by scripts/gen-ui-icons.mjs from design/assets/icons/ui/*.svg. Do not edit.
// The owner's custom icon set: one filled path (even-odd) on a square grid of \`size\`, drawn in
// currentColor by ui/Icon.svelte.

export interface UiIconShape {
  /** The square viewBox's side. */
  size: number;
  d: string;
}

export const UI_ICONS = {
${entries}
} as const satisfies Record<string, UiIconShape>;

export type UiIconName = keyof typeof UI_ICONS;
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT, renderUiIcons());
  console.log(`wrote ${path.relative(WEB, OUT)}`);
}
