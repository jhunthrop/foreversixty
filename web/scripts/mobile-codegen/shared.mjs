// web/scripts/mobile-codegen/shared.mjs
// What every native-app generator shares: the repo root, the do-not-edit header, names, and the
// write step. Each generator is a pure `generate()` that returns { path: text }; its vitest drift
// check compares that with the checked-in files, and running the script writes them.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

export const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');

export const IOS_ROOT = join(REPO_ROOT, 'apps/ios');
export const ANDROID_ROOT = join(REPO_ROOT, 'apps/android');
export const KOTLIN_SRC = 'src/main/kotlin/gg/foreversixty/app';

/** `// Generated by <script> from <sources>. Generated, do not edit.` */
export function header(script, sources) {
  return `// Generated by ${script} from ${sources.join(' and ')}. Generated, do not edit.`;
}

export const repoPath = (absolute) => relative(REPO_ROOT, absolute);

export const readRepoFile = (path) => readFileSync(join(REPO_ROOT, path), 'utf8');

/** snake_case or kebab-case to lowerCamel, the way Swift's convertFromSnakeCase reads a key. */
export function camel(key) {
  return key.replace(/[_-]+([a-zA-Z0-9])/g, (_, c) => c.toUpperCase());
}

export const pascal = (key) => {
  const c = camel(key);
  return c.charAt(0).toUpperCase() + c.slice(1);
};

/** Writes every { path: text } output, creating folders as needed. */
export function writeOutputs(outputs) {
  for (const [file, text] of Object.entries(outputs)) {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, text);
  }
}

/** Runs `generate` and writes its outputs when the calling module is the entry script. */
export function runIfMain(metaUrl, generate) {
  if (process.argv[1] === fileURLToPath(metaUrl)) writeOutputs(generate());
}

/** Fails generation loudly: a generator never guesses. */
export function fail(message) {
  throw new Error(`mobile codegen: ${message}`);
}

/** One-line doc text: whitespace collapsed, comment terminators defused. */
export function docLine(text) {
  return String(text ?? '')
    .replace(/\s+/g, ' ')
    .replace(/\*\//g, '* /')
    .trim();
}
