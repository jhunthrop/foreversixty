// web/src/lib/sim/preset-sets.ts
// What each static preset sends per spec and level, generated in Go so the page's default
// figure is the published one:
// - Raid-buffed's consumables (owner ruling, round 5): the raid preset resolved for each spec,
//   cut to the items the level can use, with the class kit of that level on top -- exactly
//   what the BiS ranker, the tier list and spec-breakdown send (sim/request/raid-consumes.json).
// - Bare's buffs and consumables (owner ruling, round 6): the class kit at that level, what the
//   ranker's bare pass sends for every band below 60 (sim/request/published-presets.json).
// Both are synced into src/data/generated by scripts/sync-raid-preset.mjs and held to the
// published setup by their Go tests.
//
// The tables are their own chunk, loaded on demand rather than carried in the planner and
// sim islands' boot bundles (scripts/check-island-size.mjs). Every path that applies a spec's
// preset (the stores' adopt, the planner's live figure and card sim) awaits loadPresetSets()
// first; asking for a spec before that is a programming error and throws, so a page can never
// quietly sim a preset with its spec's half missing.

/** One row of a spec's raid consumables: in force from `from_level` until the next row's. */
interface LevelConsumes {
  from_level: number;
  consumes: readonly string[];
}

/** One row of a spec's bare set: in force from `from_level` until the next row's. */
export interface LevelSet {
  from_level: number;
  buffs: readonly string[];
  consumes: readonly string[];
}

type RaidConsumesTable = Readonly<Record<string, readonly LevelConsumes[]>>;
type BareTable = Readonly<Record<string, readonly LevelSet[]>>;

const EMPTY_SET: LevelSet = { from_level: 1, buffs: [], consumes: [] };

let raidTable: RaidConsumesTable | null = null;
let bareTable: BareTable | null = null;
let loading: Promise<void> | null = null;

/** Loads both tables once; every later call resolves at once. */
export function loadPresetSets(): Promise<void> {
  loading ??= Promise.all([
    import('../../data/generated/raid-consumes.json'),
    import('../../data/generated/bare-preset.json'),
  ]).then(([raid, bare]) => {
    raidTable = raid.default as RaidConsumesTable;
    bareTable = bare.default as BareTable;
  });
  return loading;
}

function rowAt<T extends { from_level: number }>(
  rows: readonly T[] | undefined,
  level: number,
): T | undefined {
  return (rows ?? []).filter((row) => row.from_level <= level).at(-1);
}

function loaded<T>(table: T | null, spec: string): T {
  if (table === null) {
    throw new Error(`preset sets for ${spec} asked for before loadPresetSets() finished`);
  }
  return table;
}

/** The raid set for a spec key at a level. No spec (no character yet) and an unknown spec
 *  carry none. Throws if the tables have not been loaded. */
export function raidConsumesAt(spec: string, level: number): readonly string[] {
  if (spec === '') return [];
  return rowAt(loaded(raidTable, spec)[spec], level)?.consumes ?? [];
}

/** The bare set (the class kit) for a spec key at a level. No spec and an unknown spec carry
 *  nothing. Throws if the tables have not been loaded. */
export function bareSetAt(spec: string, level: number): LevelSet {
  if (spec === '') return EMPTY_SET;
  return rowAt(loaded(bareTable, spec)[spec], level) ?? EMPTY_SET;
}
