// The native apps' API models and endpoints are generated from api/openapi.yaml
// (web/scripts/gen-mobile-api.mjs). This fails when the checked-in Swift or Kotlin differs from
// a fresh generation: after editing the spec run `node web/scripts/gen-mobile-api.mjs` and commit.
import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
// @ts-expect-error plain .mjs script, no type declarations
import { OUTPUTS, generate } from '../../../scripts/gen-mobile-api.mjs';
// @ts-expect-error plain .mjs script, no type declarations
import { buildModel } from '../../../scripts/mobile-codegen/openapi-model.mjs';

const HINT = 'run `node web/scripts/gen-mobile-api.mjs` and commit the result';

const spec = (body: string) => `
paths:
  /v1/thing/{id}:
    get:
      operationId: getThing
      tags: [app]
      parameters: [{ name: id, in: path, required: true, schema: { type: integer } }]
      responses:
        '200':
          x-fixtures: [thing]
          content:
            application/json:
              schema:
                allOf:
                  - $ref: '#/components/schemas/Envelope'
                  - { type: object, properties: { data: { $ref: '#/components/schemas/Thing' } } }
components:
  schemas:
    Envelope: { type: object }
${body}`;

describe('mobile API codegen', () => {
  const generated = generate() as Record<string, string>;

  it.each(Object.values(OUTPUTS) as string[])('%s matches the generator', (file) => {
    expect(readFileSync(file, 'utf8'), HINT).toBe(generated[file]);
  });

  it('every output carries the do-not-edit header', () => {
    for (const text of Object.values(generated)) {
      expect(text).toMatch(/^\/\/ Generated by web\/scripts\/gen-mobile-api\.mjs .*Generated, do not edit\./);
    }
  });

  it('reads optionality, nullability, maps and renames from the spec', () => {
    const model = buildModel(
      spec(`    Thing:
      type: object
      required: [id, tags, note]
      properties:
        id: { type: integer, format: int64 }
        tags: { type: array, items: { type: string } }
        note: { type: [string, "null"] }
        stats: { type: object, additionalProperties: { type: number } }
        class: { type: string, x-name: className }
        open: { type: object, additionalProperties: true }`),
    );
    const [thing] = model.types;
    const field = (name: string) => thing.fields.find((f: { name: string }) => f.name === name);
    expect(field('id')).toMatchObject({ optional: false, type: { kind: 'scalar', scalar: 'int64' } });
    expect(field('tags')).toMatchObject({ optional: false, type: { kind: 'array' } });
    expect(field('note')).toMatchObject({ optional: true });
    expect(field('stats')).toMatchObject({ optional: true, type: { kind: 'map' } });
    expect(field('className')).toMatchObject({ json: 'class' });
    expect(field('open')).toMatchObject({ type: { kind: 'json' } });
    expect(model.operations[0]).toMatchObject({ id: 'getThing', status: 200, fixture: 'thing' });
  });

  it('refuses a reserved word without an x-name and an untitled inline object', () => {
    expect(() =>
      buildModel(spec(`    Thing: { type: object, properties: { in: { type: integer } } }`)),
    ).toThrow(/reserved word/);
    expect(() =>
      buildModel(
        spec(
          `    Thing: { type: object, properties: { sub: { type: object, properties: { a: { type: string } } } } }`,
        ),
      ),
    ).toThrow(/needs a title/);
  });
});
