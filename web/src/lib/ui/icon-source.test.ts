// The one-icon-source guard (owner 2026-11-09): every UI glyph on the site is drawn from
// lib/ui/ui-icons.ts by ui/Icon.svelte, ui/Icon.astro or lib/ui/icon.ts. A component that ships
// its own <svg>, its own path data or an svg data URI fails here unless it is on the allowlist
// below, which holds only charts, art and brand marks, each with the reason it is not an icon.
import { readdirSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';

const SRC = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');

/** Raw SVG drawing: an element, path data in markup, or an inline svg image. */
const RAW_SVG =
  /<(svg|path|circle|rect|line|polyline|polygon|ellipse)\b|data:image\/svg\+xml|createElementNS\(/;

/** Files allowed to draw SVG themselves, relative to web/src. */
const ALLOWED: Readonly<Record<string, string>> = {
  'lib/ui/icon.ts': 'the shared icon attributes and the mask builder',
  'lib/ui/listbox-render.ts': "the listbox's DOM builder, drawing ui-icons shapes",
  'components/ui/Icon.svelte': 'the icon component',
  'components/ui/Icon.astro': "the icon component's server twin",
  'components/DiscordMark.astro': 'brand mark: the Discord logo',
  'components/ui/FrameCorners.svelte': 'art: the frame filigree',
  'components/ui/Spark.svelte': 'chart: the sparkline',
  'components/character/ChartPlot.svelte': 'chart: the history plot',
  'components/chart/OverviewBrush.svelte': 'chart: the overview brush',
  'components/report/ResourceGraphs.svelte': 'chart: the resource graphs',
  'components/sim/SimTimeline.svelte': 'chart: the sim timeline',
  'components/sim/TimelineBrush.svelte': "chart: the timeline's brush",
  'lib/sim/timeline-draw.ts': "chart: the timeline's marks",
  'components/ui/TalentTree.svelte': "chart: the talent tree's connectors",
};

const SOURCE_FILE = /\.(astro|svelte|ts|css)$/;

function sourceFiles(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return sourceFiles(full);
    return SOURCE_FILE.test(entry.name) && !entry.name.endsWith('.test.ts') ? [full] : [];
  });
}

/** The icon source's one module per icon (generated by scripts/gen-ui-icons.mjs). */
const ICON_MODULES = 'lib/ui/icons/';

/** Comments name svg elements in prose ("one hidden <svg> of ..."); only code counts. */
const withoutComments = (text: string): string =>
  text
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/^\s*\/\/.*$/gm, '');

describe('the one icon source', () => {
  const files = sourceFiles(SRC).map((file) => path.relative(SRC, file).split(path.sep).join('/'));

  it('draws every UI glyph through ui/Icon, never a raw svg in a component', () => {
    const raw = files.filter(
      (file) =>
        !(file in ALLOWED) &&
        !file.startsWith(ICON_MODULES) &&
        RAW_SVG.test(withoutComments(readFileSync(path.join(SRC, file), 'utf8'))),
    );
    expect(raw).toEqual([]);
  });

  it('keeps no allowlist entry for a file that is gone or no longer draws', () => {
    const stale = Object.keys(ALLOWED).filter(
      (file) =>
        !files.includes(file) || !RAW_SVG.test(withoutComments(readFileSync(path.join(SRC, file), 'utf8'))),
    );
    expect(stale).toEqual([]);
  });
});
