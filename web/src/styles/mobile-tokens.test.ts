// The native apps' design tokens are generated from tokens.css (web/scripts/gen-mobile-tokens.mjs).
// This fails when the checked-in Swift or Kotlin differs from a fresh generation: after editing
// tokens.css run `node web/scripts/gen-mobile-tokens.mjs` and commit the result.
import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
// @ts-expect-error plain .mjs script, no type declarations
import { KOTLIN_OUT, SWIFT_OUT, buildModel, generate, parseColor } from '../../scripts/gen-mobile-tokens.mjs';

const CHECK_IN_HINT = 'run `node web/scripts/gen-mobile-tokens.mjs` and commit the result';

describe('mobile design tokens', () => {
  const generated = generate();

  it('iOS DesignTokens.swift matches the generator', () => {
    expect(readFileSync(SWIFT_OUT, 'utf8'), CHECK_IN_HINT).toBe(generated.swift);
  });

  it('Android Tokens.kt matches the generator', () => {
    expect(readFileSync(KOTLIN_OUT, 'utf8'), CHECK_IN_HINT).toBe(generated.kotlin);
  });

  it('both files carry the do-not-edit header', () => {
    expect(generated.swift).toMatch(/^\/\/ Generated by .*Generated, do not edit\./);
    expect(generated.kotlin).toMatch(/^\/\/ Generated by .*Generated, do not edit\./);
  });

  it('covers class, rarity and brand colours', () => {
    const names = new Set((buildModel(readFileSync(new URL('./tokens.css', import.meta.url), 'utf8')).colors as { name: string }[]).map((c) => c.name));
    for (const name of ['gold', 'bg', 'classHunter', 'rarityEpic', 'rarityEpicText', 'kill']) {
      expect(names.has(name), name).toBe(true);
    }
  });

  it('parses hex and rgba colours', () => {
    expect(parseColor('#abc')).toEqual({ rgb: 0xaabbcc, alpha: 1 });
    expect(parseColor('rgba(229, 185, 85, 0.17)')).toEqual({ rgb: 0xe5b955, alpha: 0.17 });
    expect(parseColor('var(--x)')).toBeNull();
  });
});
