"""addon-data.json rendered as the Lua chunk the addon loads.

The file is committed so the addon is installable straight from a
checkout and so a release zip needs no build step. CI's drift gate
(`python -m pipeline addon-data --check`) is what keeps it honest.

The chunk sets `ns.Data` and returns it, which is the pattern every
module in `addon/ForeverSixty/` uses: in the game `...` is
`addonName, addonTable` so `ns` is the addon table; under busted's
`require`, the second value is the chunk's filepath (a string, not
nil), so `ns = ns or {}` would never allocate a table there. Instead
`ns = type(ns) == "table" and ns or {}` only keeps `ns` when it is
already a table and falls back to a fresh one otherwise, and the
return value is what the spec receives.
"""

from __future__ import annotations

from pathlib import Path

from pipeline.addonbis import (
    FILTER_KIND_OF_SOURCE,
    SOURCE_FILTER_KINDS,
    SOURCE_KIND_CODES,
    STANDINGS,
    AddonBisError,
)
from pipeline.addondata import build_addon_data
from pipeline.models import AddonData

LUA_PATH = Path("../addon/ForeverSixty/Data.lua")

GENERATED = "-- Code generated by `python -m pipeline addon-data`. DO NOT EDIT."


def _quote(value: str) -> str:
    """A Lua short string literal. Backslash first, or the quote escape is re-escaped."""
    escaped = value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    return f'"{escaped}"'


def _number(value: float) -> str:
    """A Lua number literal, integers without a trailing .0."""
    return str(int(value)) if float(value).is_integer() else repr(float(value))


def _class_lua(slug: str, tabs: list) -> str:
    lines = [f"\t\t[{_quote(slug)}] = {{", "\t\t\ttabs = {"]
    for tab in tabs:
        lines.append(f"\t\t\t\t{{ name = {_quote(tab.name)}, talents = {{")
        for talent in tab.talents:
            lines.append(
                f"\t\t\t\t\t{{ name = {_quote(talent.name)}, tier = {talent.tier}, "
                f"column = {talent.column}, maxRank = {talent.max_rank}, node = {talent.node} }},"
            )
        lines.append("\t\t\t\t} },")
    lines.append("\t\t\t},")
    lines.append("\t\t},")
    return "\n".join(lines)


def _race_ids_lua(ids: dict[str, int]) -> str:
    """`, raceSpellId = { ["undead"] = .., .. }` for a line whose rank a race's
    row changes (round 13), else nothing. Keys are the site's race slugs,
    quoted because `night-elf` is no bare Lua name."""
    if not ids:
        return ""
    pairs = ", ".join(f"[{_quote(race)}] = {ids[race]}" for race in sorted(ids))
    return f", raceSpellId = {{ {pairs} }}"


def _rotation_line_lua(line) -> str:
    races = _race_ids_lua(line.race_spell_ids)
    return (
        f"{{ spellId = {line.spell_id}, name = {_quote(line.name)}, "
        f"condition = {_quote(line.condition)}{races} }}"
    )


def _pool(literals: list[str]) -> dict[str, int]:
    """Each distinct Lua table literal -> its 1-based slot in a shared pool, in
    first-use order, so the render is stable."""
    index: dict[str, int] = {}
    for literal in literals:
        index.setdefault(literal, len(index) + 1)
    return index


def _pool_lua(name: str, index: dict[str, int]) -> list[str]:
    """`local <name> = { <literal>, ... }`, declared above `ns.Data`. A local
    goes out of scope when the chunk returns, so only the tables the data
    still points at stay on the heap."""
    return [f"local {name} = {{"] + [f"\t{literal}," for literal in index] + ["}"]


#: The shared pool of rotation lines (_rotations_lua).
ROTATION_POOL = "rotationLines"


def _rotations_lua(rotations: dict) -> tuple[list[str], list[str]]:
    """The rotation pool, then `rotations[spec] = { { level, lines = { line, ... } }, ... }`.

    A band repeats every line the band before it kept, so each distinct line
    is ONE table in a pool that every band of every spec points at: 5,786
    lines were 1,086 distinct on 1.60.1.70790, and the copies were 1.2 MB of
    the Lua 5.1 heap (DATA_LUA_IDLE_BUDGET_KB's note in tests/test_addondata.py).
    The addon only reads a line (Rotation.lua copies one before changing its
    rank), so a shared table is safe. Returns (pool lines, data lines)."""
    index = _pool(
        [
            _rotation_line_lua(line)
            for spec in sorted(rotations)
            for band in rotations[spec]
            for line in band.lines
        ]
    )
    lines = ["\trotations = {"]
    for spec in sorted(rotations):
        lines.append(f"\t\t[{_quote(spec)}] = {{")
        for band in rotations[spec]:
            refs = ", ".join(
                f"{ROTATION_POOL}[{index[_rotation_line_lua(line)]}]" for line in band.lines
            )
            lines.append(f"\t\t\t{{ level = {band.level}, lines = {{ {refs} }} }},")
        lines.append("\t\t},")
    lines.append("\t},")
    return _pool_lua(ROTATION_POOL, index), lines


def _source_kind_code(source_kind: str) -> str:
    code = SOURCE_KIND_CODES.get(source_kind)
    if code is None:
        raise AddonBisError(
            f"no Lua code for source_kind {source_kind!r}; add it to SOURCE_KIND_CODES"
        )
    return code


#: The field separator inside a packed BiS pick string (_bis_pick_packed).
BIS_FIELD_SEPARATOR = "|"


def _bis_field(value: str) -> str:
    if BIS_FIELD_SEPARATOR in value:
        raise AddonBisError(f"{value!r} contains the BiS field separator {BIS_FIELD_SEPARATOR!r}")
    return value


#: The site's filter kinds as one letter each, for the tail's head entry (the pick's own
#: kinds): SOURCE_KIND_CODES' letters, world_drop's B folded into world's W.
FILTER_KIND_CODES: dict[str, str] = {kind: SOURCE_KIND_CODES[kind] for kind in SOURCE_FILTER_KINDS}

#: A reputation standing as one lower-case letter, after a kind's letter.
STANDING_CODES: dict[str, str] = {standing: standing[0] for standing in STANDINGS}

#: Separators inside the by-kind tail (one `|` field): entries, then an entry's fields,
#: then the ids inside its not_with list. None of them is `|`, and none can appear in a
#: number or a letter code, so the tail never shifts the fields before it.
BIS_ENTRY_SEPARATOR = ";"
BIS_ENTRY_FIELD_SEPARATOR = ","
BIS_NOT_WITH_SEPARATOR = "+"
#: The head entry's mark (the pick's own filter facts), and the two-hander mark; neither
#: is a digit or a letter, so `C!7000` never reads as another id.
BIS_HEAD_MARK = "*"
BIS_TWO_HAND_MARK = "!"


def _not_with(ids: list[int]) -> str:
    return BIS_NOT_WITH_SEPARATOR.join(str(other) for other in ids)


def _pick_head(item) -> str:
    """The tail's head entry, `*!RhVh,19513`: the two-hander mark, the pick's own filter
    kinds each with the standing it asks, then the ids its pair mate must not hold. Empty
    when the pick's source_kind alone describes it. The decoder reads an entry with no
    kind letters as the pick's own code's kind."""
    own = FILTER_KIND_OF_SOURCE.get(item.source_kind)
    kinds = list(item.kinds) or ([own] if own else [])
    gated = [kind for kind in kinds if item.standings.get(kind)]
    letters = (
        "".join(
            FILTER_KIND_CODES[kind] + STANDING_CODES.get(item.standings.get(kind, ""), "")
            for kind in kinds
        )
        if item.kinds or gated
        else ""
    )
    mark = (BIS_TWO_HAND_MARK if item.two_hand else "") + letters
    if not mark and not item.not_with:
        return ""
    head = BIS_HEAD_MARK + mark
    if item.not_with:
        head += BIS_ENTRY_FIELD_SEPARATOR + _not_with(item.not_with)
    return head


def _kind_entry(entry, source_index: dict[str, int]) -> str:
    """`Dh!26686,12,1234+5678`: the kind letter, a standing letter, the two-hander mark,
    the id; the place's 1-based bisSources index (empty for none); the ids the pair
    mate must not hold, when any."""
    if entry.source and entry.source not in source_index:
        raise AddonBisError(f"bisSources does not list the by-kind place {entry.source!r}")
    fields = [
        _source_kind_code(entry.source_kind)
        + STANDING_CODES.get(entry.standing, "")
        + (BIS_TWO_HAND_MARK if entry.two_hand else "")
        + str(entry.item_id),
        str(source_index[entry.source]) if entry.source else "",
        _not_with(entry.not_with),
    ]
    while fields[-1] == "":
        fields.pop()
    return BIS_ENTRY_FIELD_SEPARATOR.join(fields)


def _bis_tail(item, source_index: dict[str, int]) -> str:
    """The by-kind tail: the head entry, then one entry per by_kind item in rank order,
    `;`-joined. Empty when the pick carries nothing beyond its own fields."""
    head = _pick_head(item)
    entries = ([head] if head else []) + [
        _kind_entry(entry, source_index) for entry in item.by_kind
    ]
    return BIS_ENTRY_SEPARATOR.join(entries)


def _bis_pick_packed(item, source_index: dict[str, int] | None = None) -> str:
    """One pick as ONE string, `|`-joined in the order
    `item_id|kind|source|chance|alt1_id|alt1_kind|alt1_source|alt2_id|
    alt2_kind|alt2_source` (contract 1's "physical encoding" note in
    docs/contracts/addon-v2.md). A string per pick instead of a table plus
    a table per alternative is what keeps Data.lua's loaded heap under the
    addon's idle budget; Gear.pick decodes it back into the logical
    table. `kind` is the single-letter SOURCE_KIND_CODES code, `chance` a
    plain number, and a missing field is empty, so the positions never
    shift; trailing empty fields are trimmed (Gear.decodePick reads a
    missing field as empty).

    The source filter's facts (2026-11-13) follow the alternatives as ONE more
    field after ONE empty one: `...|alt2_source||<tail>`. The empty field is
    where a third alternative's id would be, which is how the decoder knows the
    alternatives have ended; the tail (_bis_tail) is the pick's own kinds and the
    best item of every other kind, so a slot can be re-picked in game with a
    kind off. A pick with no such facts packs exactly as before."""
    fields = [
        str(item.item_id),
        _source_kind_code(item.source_kind),
        _bis_field(item.source),
        _number(item.chance) if item.chance is not None else "",
    ]
    for alternative in item.alternatives:
        fields += [
            str(alternative.item_id),
            _source_kind_code(alternative.source_kind),
            _bis_field(alternative.source),
        ]
    tail = _bis_tail(item, source_index or {})
    if tail:
        fields += ["", tail]
    while fields[-1] == "":
        fields.pop()
    return BIS_FIELD_SEPARATOR.join(fields)


def _source_index(bis_sources: list[str]) -> dict[str, int]:
    """Place -> its 1-based position in Data.lua's bisSources list."""
    return {source: index for index, source in enumerate(bis_sources, start=1)}


def _bis_lua(bis: dict, bis_sources: list[str] | None = None) -> list[str]:
    """`bis[spec][band][faction][slot] = "itemId|sourceKindCode|source|chance|..."`,
    one packed string per pick (_bis_pick_packed's own doc). Until task
    L1.2's fix round 2 a pick was the positional table `{ itemId,
    sourceKindCode[, source] }`; the size reasoning below was written for
    that table and holds for the packed string too.
    -- ids only (addonbis.py's own load-bearing decision) and positional
    rather than named fields, and faction/slot as bare Lua identifiers
    rather than quoted keys, because this table is the addition the lane
    brief's size budget is about: named fields alone would nearly double it
    across 27 specs. Tooltip.lua's SOURCE_KIND_NAMES decodes the
    single-letter code back for the tooltip's muted source line; `source`
    (the third, optional element -- left out of the table literal entirely
    for a pick with none, rather than an empty string, saving two bytes
    each) is the short place name that line reads beside it."""
    source_index = _source_index(bis_sources or [])
    lines = ["\tbis = {"]
    for spec in sorted(bis):
        lines.append(f"\t\t[{_quote(spec)}] = {{")
        for band in bis[spec]:
            lines.append(f"\t\t\t[{band.level}] = {{")
            for faction in sorted(band.factions):
                lines.append(f"\t\t\t\t{faction} = {{")
                for slot in sorted(band.factions[faction]):
                    packed = _bis_pick_packed(band.factions[faction][slot], source_index)
                    lines.append(f"\t\t\t\t\t{slot} = {_quote(packed)},")
                lines.append("\t\t\t\t},")
            lines.append("\t\t\t},")
        lines.append("\t\t},")
    lines.append("\t},")
    return lines


def _bis_weights_lua(bis: dict) -> list[str]:
    """`bis_weights[spec][band] = { stat = weight }`, significant weights
    only (AddonBisBand.weights' own filter) -- the nightly measured weights
    Tooltip.verdictFor scores a hovered item against, in preference to the
    curated static `weights` table above (lane addon-tooltip-polish item
    4). A spec/band leveling-bis has not measured yet simply has no key,
    the same "absent, not empty" rule build_bis's own docstring states for
    a spec with no bis/<spec>.json at all."""
    lines = ["\tbis_weights = {"]
    for spec in sorted(bis):
        measured = [band for band in bis[spec] if band.weights]
        if not measured:
            continue
        lines.append(f"\t\t[{_quote(spec)}] = {{")
        for band in measured:
            pairs = ", ".join(
                f"[{_quote(stat)}] = {_number(value)}"
                for stat, value in sorted(band.weights.items())
            )
            lines.append(f"\t\t\t[{band.level}] = {{ {pairs} }},")
        lines.append("\t\t},")
    lines.append("\t},")
    return lines


def _bis_new_lua(bis: dict) -> list[str]:
    """`bis_new[spec][band][faction] = { itemId, ... }` -- the item ids
    newly best at that band, for the tooltip's "(new at <band>)" tag."""
    lines = ["\tbis_new = {"]
    for spec in sorted(bis):
        lines.append(f"\t\t[{_quote(spec)}] = {{")
        for band in bis[spec]:
            lines.append(f"\t\t\t[{band.level}] = {{")
            for faction in sorted(band.new_at_band):
                ids = ", ".join(str(item_id) for item_id in band.new_at_band[faction])
                lines.append(f"\t\t\t\t{faction} = {{ {ids} }},")
            lines.append("\t\t\t},")
        lines.append("\t\t},")
    lines.append("\t},")
    return lines


def _bis_sources_lua(bis_sources: list[str]) -> list[str]:
    """`bisSources = { "World drop", ... }`: the places the by-kind tail indexes
    into, 1-based, in the order pipeline.addonbis.build_bis_sources gives.
    Absent when no pick carries a by-kind entry."""
    if not bis_sources:
        return []
    lines = ["\tbisSources = {"]
    for source in bis_sources:
        lines.append(f"\t\t{_quote(_bis_field(source))},")
    lines.append("\t},")
    return lines


def _bis_items_lua(bis_names: dict, bis_dps: dict) -> list[str]:
    """`bisNames[itemId] = "name"` and `bisDps[itemId] = dps` (task L1.4):
    one entry per distinct pick or alternative id, so a name is stored once
    however many picks share it. Both are left out entirely when empty."""
    lines: list[str] = []
    if bis_names:
        lines.append("\tbisNames = {")
        for item_id in sorted(bis_names):
            lines.append(f"\t\t[{item_id}] = {_quote(bis_names[item_id])},")
        lines.append("\t},")
    if bis_dps:
        lines.append("\tbisDps = {")
        for item_id in sorted(bis_dps):
            lines.append(f"\t\t[{item_id}] = {_number(bis_dps[item_id])},")
        lines.append("\t},")
    return lines


#: The shared pool of talent points (_default_builds_lua).
POINT_POOL = "talentPoints"


def _point_lua(point) -> str:
    return "{" + ",".join(str(n) for n in point) + "}"


def _default_builds_lua(default_builds: dict) -> tuple[list[str], list[str]]:
    """The point pool, then `defaultBuilds[spec].leveling|raid = { name, why, order = {
    {tab,tier,column}, ... } }` (docs/contracts/addon-v2.md, contract 1): the guide's why
    for the build, then one 1-based triple per point in learning order, the codec's own
    triple. A triple names no class, so 28 specs x 2 builds x 51 points share the few
    dozen distinct triples from one pool (the addon only reads them), not a table per
    point. Returns (pool lines, data lines)."""
    builds = [
        default_builds[spec][kind]
        for spec in sorted(default_builds)
        for kind in ("leveling", "raid")
        if kind in default_builds[spec]
    ]
    index = _pool([_point_lua(point) for build in builds for point in build.order])
    lines = ["\tdefaultBuilds = {"]
    for spec in sorted(default_builds):
        lines.append(f"\t\t[{_quote(spec)}] = {{")
        for kind in ("leveling", "raid"):
            build = default_builds[spec].get(kind)
            if build is None:
                continue
            order = ", ".join(f"{POINT_POOL}[{index[_point_lua(point)]}]" for point in build.order)
            lines.append(
                f"\t\t\t{kind} = {{ name = {_quote(build.name)}, why = {_quote(build.why)},"
                f" order = {{ {order} }} }},"
            )
        lines.append("\t\t},")
    lines.append("\t},")
    return _pool_lua(POINT_POOL, index), lines


def _spec_icons_lua(spec_icons: dict[str, str]) -> list[str]:
    """`specIcons[spec] = "<client icon name>"` (contract 1): the icon the
    Builds pane draws beside each spec, the planner's own."""
    lines = ["\tspecIcons = {"]
    for spec in sorted(spec_icons):
        lines.append(f"\t\t[{_quote(spec)}] = {_quote(spec_icons[spec])},")
    lines.append("\t},")
    return lines


def _dps_per_point_lua(dps_per_point: dict) -> list[str]:
    """`dpsPerPoint[spec] = { reference, dps, healing, weaponDps, [band] = {
    reference, dps, weaponDps } }` (contract 1; bands from task L1.5). A
    spec with no entry is left out, never written as zero: the addon reads
    a missing key as "show score units"."""
    lines = ["\tdpsPerPoint = {"]
    for spec in sorted(dps_per_point):
        entry = dps_per_point[spec]
        healing = "true" if entry.healing else "false"
        head = (
            f"\t\t[{_quote(spec)}] = {{ reference = {_quote(entry.reference)}, "
            f"dps = {_number(entry.dps)}, healing = {healing}"
        )
        if not entry.bands and not entry.weapon_dps:
            lines.append(head + " },")
            continue
        # Task L1.5: the level-60 raid figure stays at the spec level for the
        # current reader; each band's own figures sit under its band key.
        lines.append(head + f", weaponDps = {_number(entry.weapon_dps)},")
        for band in sorted(entry.bands):
            row = entry.bands[band]
            lines.append(
                f"\t\t\t[{band}] = {{ reference = {_quote(row.reference)}, "
                f"dps = {_number(row.dps)}, weaponDps = {_number(row.weapon_dps)} }},"
            )
        lines.append("\t\t},")
    lines.append("\t},")
    return lines


def _encounter_needs_lua(encounter_needs: dict) -> list[str]:
    """`encounterNeeds[npcId] = { buffs = {...}, debuffs = {...}, resist = "fire" }`
    (contract 1); `resist` is left out for a boss with none, which Lua reads
    as nil."""
    lines = ["\tencounterNeeds = {"]
    for npc_id in sorted(encounter_needs):
        needs = encounter_needs[npc_id]
        buffs = ", ".join(str(spell) for spell in needs.buffs)
        debuffs = ", ".join(str(spell) for spell in needs.debuffs)
        resist = f", resist = {_quote(needs.resist)}" if needs.resist is not None else ""
        lines.append(
            f"\t\t[{npc_id}] = {{ buffs = {{ {buffs} }}, debuffs = {{ {debuffs} }}{resist} }},"
        )
    lines.append("\t},")
    return lines


def _ability_levels_lua(ability_levels: dict) -> list[str]:
    """`abilityLevels[spellId] = level` (contract 1), one id per line, ids ascending."""
    lines = ["\tabilityLevels = {"]
    for spell_id in sorted(ability_levels):
        lines.append(f"\t\t[{spell_id}] = {ability_levels[spell_id]},")
    lines.append("\t},")
    return lines


def render_lua(data: AddonData) -> str:
    rotation_pool, rotations = _rotations_lua(data.rotations)
    point_pool, default_builds = _default_builds_lua(data.default_builds)
    lines = [
        GENERATED,
        "-- Source: data/builds/<build>/addon-data.json",
        "local _, ns = ...",
        'ns = type(ns) == "table" and ns or {}',
        "",
        "-- Tables many entries below share; the addon only reads them.",
        *rotation_pool,
        *point_pool,
        "",
        "ns.Data = {",
        f"\tbuild = {_quote(data.build)},",
        "\tclasses = {",
    ]
    for slug in sorted(data.classes):
        lines.append(_class_lua(slug, data.classes[slug].tabs))
    lines.append("\t},")
    lines.append("\tweights = {")
    for spec in sorted(data.weights):
        pairs = ", ".join(
            f"[{_quote(stat)}] = {_number(value)}"
            for stat, value in sorted(data.weights[spec].items())
        )
        lines.append(f"\t\t[{_quote(spec)}] = {{ {pairs} }},")
    lines.append("\t},")
    lines.extend(rotations)
    lines.extend(_bis_lua(data.bis, data.bis_sources))
    lines.extend(_bis_new_lua(data.bis))
    lines.extend(_bis_weights_lua(data.bis))
    lines.extend(_bis_items_lua(data.bis_names, data.bis_dps))
    lines.extend(_bis_sources_lua(data.bis_sources))
    lines.extend(default_builds)
    lines.extend(_spec_icons_lua(data.spec_icons))
    lines.extend(_dps_per_point_lua(data.dps_per_point))
    lines.extend(_encounter_needs_lua(data.encounter_needs))
    lines.extend(_ability_levels_lua(data.ability_levels))
    lines.append("}")
    lines.append("")
    lines.append("return ns.Data")
    return "\n".join(lines) + "\n"


def write_lua(
    build: str,
    root: Path = Path("builds"),
    curated_dir: Path = Path("curated"),
    lua_path: Path = LUA_PATH,
    data: AddonData | None = None,
) -> Path:
    lua_path.parent.mkdir(parents=True, exist_ok=True)
    data = data or build_addon_data(build, root=root, curated_dir=curated_dir)
    lua_path.write_text(render_lua(data), encoding="utf-8")
    return lua_path


def lua_has_drifted(
    build: str,
    root: Path = Path("builds"),
    curated_dir: Path = Path("curated"),
    lua_path: Path = LUA_PATH,
    data: AddonData | None = None,
) -> bool:
    wanted = render_lua(data or build_addon_data(build, root=root, curated_dir=curated_dir))
    return not lua_path.exists() or lua_path.read_text(encoding="utf-8") != wanted
