"""`simbuffs.json`: what to call every id a sim request may name.

Parity contract 10.4, for design section 4.3's full buff panel. An id in
`sim/request/IDS.md` is a protobuf field or enum-value name, not a spell
id, so nothing downstream can render it: this file is the display name
and icon per id, resolved once at build time.

IDS.md is generated by the sim module from the engine's own descriptors,
so it is parsed here rather than restated -- an id the engine adds shows
up as a build that needs a name, not as a panel row nobody notices is
missing.

The join is by normalised name, with the two spellings IDS.md itself
documents (the id, and the id without its leading enum-name token) and
the singular of each for the engine's plural fields. 151 of the 165 ids
resolve that way on the pinned engine and build; the other 14 are
`data/curated/simbuffs.json`. An id that resolves through neither is a
hard error: a row with a blank name and `icons/.webp` is worse than a
build that refuses to emit.
"""

from __future__ import annotations

import json
import logging
import re
from collections.abc import Callable
from pathlib import Path

from pipeline.csvio import read_csv
from pipeline.curated import parse_sources
from pipeline.forkdb import ForkDatabase
from pipeline.icons import icon_names, resolve_icon
from pipeline.models import BuffOverride, SimBuffEffect, SimBuffEntry, SimBuffsFile

SIMBUFFS = "simbuffs.json"
logger = logging.getLogger(__name__)

IDS_MD = Path("../sim/request/IDS.md")

#: Normalised name -> (display name, icon).
type NameTable = dict[str, tuple[str, str]]

_ROW = re.compile(r"^\| `([a-z0-9_]+(?::[a-z0-9_]+)?)` \|", re.M)
_DEBUFF_ROW = re.compile(r"^\| `([a-z0-9_]+(?::[a-z0-9_]+)?)` \| Debuffs \|", re.M)
#: A graded buff's stronger grade ("blessing_of_might:improved"): the panel
#: draws it as its base id's row, so it needs no entry of its own.
IMPROVED = ":improved"
#: The client's placeholder icon file, which several fork spell rows carry.
TEMP_ICON = "temp"
#: The IDS.md sections whose ids this file covers. "Professions" is
#: deliberately absent: those are character slugs, not buffs.
_SECTIONS = ("## Buffs", "## Consumables")


class BuffError(SystemExit):
    """An IDS.md id has no name the build can show."""


def normalise(name: str) -> str:
    """A display name as an id-shaped key: lowercase, apostrophes gone."""
    return re.sub(r"[^a-z0-9]+", "_", name.lower().replace("'", "")).strip("_")


def ids_md_ids(text: str) -> list[str]:
    """Every buff and consumable id IDS.md lists, sorted and deduplicated.

    Three ids (`scroll_of_agility`, `scroll_of_protection`,
    `scroll_of_strength`) are in both tables, which is why this is a set
    and not a concatenation. A missing section is an error rather than an
    empty answer: IDS.md is generated, and a shape change there must not
    silently empty the buff panel.
    """
    found: set[str] = set()
    for marker in _SECTIONS:
        if marker not in text:
            raise BuffError(f"{marker!r} is not in IDS.md; its shape changed")
        section = text.split(marker, 1)[1].split("\n## ", 1)[0]
        found |= {buff_id for buff_id in _ROW.findall(section) if not buff_id.endswith(IMPROVED)}
    return sorted(found)


def consumable_ids(text: str) -> frozenset[str]:
    """The ids IDS.md's Consumables section lists: things in the player's
    bag (a flask, a potion, a food, an oil), so their names join the item
    tables first."""
    if _SECTIONS[1] not in text:
        raise BuffError(f"{_SECTIONS[1]!r} is not in IDS.md; its shape changed")
    section = text.split(_SECTIONS[1], 1)[1].split("\n## ", 1)[0]
    return frozenset(_ROW.findall(section))


def named_part(buff_id: str) -> tuple[bool, str]:
    """(qualified, the part a name joins on). A weapon imbue's id names its
    hand and field first ("main_hand_imbue:brilliant_wizard_oil"); its name
    and icon are the oil's, and the page says which hand."""
    qualifier, _, rest = buff_id.partition(":")
    return (True, rest) if rest else (False, qualifier)


def _candidates(buff_id: str) -> list[str]:
    """The spellings a display name may take for this id, best first."""
    out: list[str] = []
    for base in (buff_id, buff_id[:-1] if buff_id.endswith("s") else None):
        if base is None:
            continue
        out.append(base)
        if "_" in base:
            out.append(base.split("_", 1)[1])
    return out


def fork_tables(fork: ForkDatabase) -> list[NameTable]:
    """The fork's own icon tables: name and icon in one row, so no client
    lookup is needed for the 97 ids they cover."""
    return [_table_from(fork.spell_icon_rows), _table_from(fork.item_icon_rows)]


def fork_item_table(fork: ForkDatabase) -> NameTable:
    """The fork's item icon rows alone: a weapon imbue that is an item (an
    oil, a stone, a poison) takes the item's icon, the one in the player's
    bag, before a same-named enchant spell's (Wizard Oil's spell is 'temp')."""
    return _table_from(fork.item_icon_rows)


def _table_from(rows: tuple[dict, ...]) -> NameTable:
    table: NameTable = {}
    for row in rows:
        if row.get("name") and row.get("icon"):
            table.setdefault(normalise(row["name"]), (row["name"], row["icon"]))
    return table


#: (item_id, spell_id) -> the icon the build ships for whichever is set.
type IconFor = Callable[[int, int], str]


#: The raw tables `client_tables` reads; a merge-only night may lack them.
CLIENT_NAME_TABLES = ("ManifestInterfaceData.csv", "SpellMisc.csv", "Item.csv")


def client_tables(build_dir: Path, raw: Path) -> tuple[list[NameTable], IconFor]:
    """The build's own spell and item names, with icons resolved through
    `ManifestInterfaceData` exactly as every other icon here is.

    Returns the two tables and the resolver, because a curated override
    names a client row rather than an icon and needs the same lookup.
    """
    names = icon_names(read_csv(raw / "ManifestInterfaceData.csv"))
    spell_icon = {
        int(row["SpellID"]): int(row["SpellIconFileDataID"] or 0)
        for row in read_csv(raw / "SpellMisc.csv")
        if row.get("SpellID")
    }
    item_icon = {
        int(row["ID"]): int(row["IconFileDataID"] or 0) for row in read_csv(raw / "Item.csv")
    }

    def table(path: Path, icons: dict[int, int], what: str) -> NameTable:
        built: NameTable = {}
        for row in json.loads(path.read_text(encoding="utf-8")):
            key = normalise(row["name"])
            if key in built:
                continue
            icon = resolve_icon(
                icons.get(int(row["id"]), 0), names, f"{what} {row['id']} ({row['name']})"
            )
            built[key] = (row["name"], icon)
        return built

    def icon_for(item_id: int, spell_id: int) -> str:
        if item_id:
            return resolve_icon(item_icon.get(item_id, 0), names, f"item {item_id}")
        return resolve_icon(spell_icon.get(spell_id, 0), names, f"spell {spell_id}")

    return (
        [
            table(build_dir / "spells.json", spell_icon, "spell"),
            table(build_dir / "items.json", item_icon, "item"),
        ],
        icon_for,
    )


def load_overrides(
    curated_dir: Path = Path("curated"), name: str = SIMBUFFS
) -> dict[str, BuffOverride]:
    """The curated ids, validated. A missing file is no overrides, which
    is a legal state only while every id happens to join."""
    path = curated_dir / name
    if not path.exists():
        return {}
    document = json.loads(path.read_text(encoding="utf-8"))
    parse_sources(document.get("sources", []), str(path))
    if not document.get("notes", "").strip():
        raise BuffError(f"{path} has no notes; say why each id needs a hand")
    overrides: dict[str, BuffOverride] = {}
    for key, value in document["entries"].items():
        override = BuffOverride(**value)
        if bool(override.item_id) == bool(override.spell_id):
            raise BuffError(
                f"{path} entry {key!r} must name exactly one of item_id or spell_id, "
                f"so its icon comes from the build rather than from this file"
            )
        overrides[key] = override
    return overrides


def load_effects(
    curated_dir: Path = Path("curated"), name: str = SIMBUFFS
) -> dict[str, SimBuffEffect]:
    """The curated `effects` block, validated. An id with no effect has no row."""
    path = curated_dir / name
    if not path.exists():
        return {}
    document = json.loads(path.read_text(encoding="utf-8"))
    return {
        buff_id: SimBuffEffect.model_validate(row)
        for buff_id, row in document.get("effects", {}).items()
    }


def debuff_ids(text: str) -> frozenset[str]:
    """The ids IDS.md lands in the engine's Debuffs message: those are on the target."""
    return frozenset(_DEBUFF_ROW.findall(text))


def with_effects(
    file: SimBuffsFile, effects: dict[str, SimBuffEffect], on_target: frozenset[str]
) -> SimBuffsFile:
    """Each entry with its side and its curated effect. A pure join over a file a
    full rebuild or a merge already named, so both paths publish the same fields."""
    return SimBuffsFile(
        entries={
            buff_id: entry.model_copy(
                update={
                    "target": buff_id in on_target,
                    **(dict(effects[buff_id]) if buff_id in effects else {}),
                }
            )
            for buff_id, entry in file.entries.items()
        }
    )


def override_for(buff_id: str, overrides: dict[str, BuffOverride]) -> BuffOverride | None:
    """The id's own override, else (for a weapon imbue) its oil's or totem's."""
    qualified, part = named_part(buff_id)
    return overrides.get(buff_id) or (overrides.get(part) if qualified else None)


def joined_name(
    buff_id: str,
    names: list[str],
    tables: list[NameTable],
    item_tables: list[NameTable],
    consumables: frozenset[str],
) -> tuple[str, str] | None:
    """The first table row a spelling of `names` reaches. A consumable is an
    item in the player's bag, so the item tables go first for it: a food's
    same-named recipe spell carries the Seal of Kings icon, a healing
    potion's use spell a nature icon, Wizard Oil's enchant spell 'temp'. A
    row whose icon is the client's 'temp' placeholder loses to any later
    row with real art, and is kept only when nothing else names the id."""
    order = [*item_tables, *tables] if buff_id in consumables else tables
    hits = [table[n] for n in names for table in order if n in table]
    return next((hit for hit in hits if hit[1] != TEMP_ICON), hits[0] if hits else None)


def build_simbuffs(
    ids: list[str],
    tables: list[NameTable],
    overrides: dict[str, BuffOverride],
    icon_for: IconFor,
    item_tables: list[NameTable] | None = None,
    consumables: frozenset[str] = frozenset(),
) -> SimBuffsFile:
    entries: dict[str, SimBuffEntry] = {}
    unresolved: list[str] = []
    for buff_id in ids:
        override = override_for(buff_id, overrides)
        if override is not None:
            entries[buff_id] = SimBuffEntry(
                name=override.name,
                icon=icon_for(override.item_id, override.spell_id),
            )
            continue
        found = joined_name(
            buff_id, _candidates(named_part(buff_id)[1]), tables, item_tables or [], consumables
        )
        if found is None:
            unresolved.append(buff_id)
            continue
        entries[buff_id] = SimBuffEntry(name=found[0], icon=found[1])
    if unresolved:
        raise BuffError(
            f"{len(unresolved)} IDS.md id(s) have no name in the fork database or "
            f"this build: {', '.join(unresolved)}. Add each to "
            f"data/curated/simbuffs.json with a source, or fix the join."
        )
    return SimBuffsFile(entries=dict(sorted(entries.items())))


def merge_simbuffs(
    ids: list[str],
    tables: list[NameTable],
    existing: dict[str, SimBuffEntry],
    overrides: dict[str, BuffOverride],
    item_tables: list[NameTable] | None = None,
    consumables: frozenset[str] = frozenset(),
) -> SimBuffsFile:
    """The merge-only night's `simbuffs.json`: every id IDS.md lists, kept
    as the committed file names it, with a new id (an engine buff the
    fork gained since the last full rebuild) named from the fork's own
    tables, or the client's when the raw tables are on disk. An override
    whose icon needs a client row keeps the committed entry when there
    is one. A new id nothing names is left out with a warning, and the
    build's own test (every IDS.md id is named) says so on the next run:
    the merge night must not fail over a name the full rebuild supplies.
    An id IDS.md dropped is dropped."""
    entries: dict[str, SimBuffEntry] = {}
    unresolved: list[str] = []
    for buff_id in ids:
        kept = existing.get(buff_id)
        if kept is not None:
            entries[buff_id] = kept
            continue
        override = override_for(buff_id, overrides)
        names = [normalise(override.name)] if override is not None else []
        names += _candidates(named_part(buff_id)[1])
        found = joined_name(buff_id, names, tables, item_tables or [], consumables)
        if found is None:
            unresolved.append(buff_id)
            continue
        entries[buff_id] = SimBuffEntry(name=found[0], icon=found[1])
    if unresolved:
        logger.warning(
            "simbuffs merge: %d IDS.md id(s) are new since the last full loot rebuild and "
            "have no name in the tables on disk, left unnamed until it runs: %s",
            len(unresolved),
            ", ".join(unresolved),
        )
    return SimBuffsFile(entries=dict(sorted(entries.items())))


def load_simbuffs(build_dir: Path) -> dict[str, SimBuffEntry]:
    """The committed `simbuffs.json` entries, or none before the first build."""
    path = build_dir / SIMBUFFS
    if not path.exists():
        return {}
    document = SimBuffsFile.model_validate_json(path.read_text(encoding="utf-8"))
    return dict(document.entries)
