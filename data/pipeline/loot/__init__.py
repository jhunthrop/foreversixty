def _require(path: Path, command: str) -> None:
    if not path.exists():
        raise SystemExit(f"no {path}; run `python -m pipeline {command}` for this build first")


def _pvp_ranks_with_classic_db(
    build_dir: Path, client_ranks: dict[int, int], item_rows: list[dict] | None = None
) -> dict[int, int]:
    """`pipeline.classicdb_items.honor_ranks` over this build's committed
    classic-db extract (`raw/classicdb/item_template.json`), so this runs
    the same in `write_loot_files` and the raw-CSV-free
    `merge_loot_files`. The original Classic honor sets carry no
    `ItemSparse.RequiredPVPRank` in a hotfix-only table, classic-db does;
    the title fallback covers a Forever re-itemised honor reward under a
    new id. With no extract the client's ranks stand alone."""
    extract = load_classic_item_template(build_dir)
    return honor_ranks(client_ranks, [] if extract is None else extract[0], item_rows)


def _classic_unranked(build_dir: Path) -> frozenset[int]:
    """Classic ids classic-db names with no honor rank: never backfilled
    into a pvp source (`split_pvp_sources_by_faction`)."""
    extract = load_classic_item_template(build_dir)
    return frozenset() if extract is None else frozenset(classic_unranked_ids(extract[0]))


@dataclass(frozen=True)
class _LootRun:
    """What one loot.json build produced, for the two commands' logs."""

    document: LootFile
    stats: LootStats
    pvp_faction_stats: PvpFactionStats
    reitemised: int
    superseded: dict[int, int]
    superseded_removed: int
    vendor_cost_gated: int
    superseded_marked: int
    quest_class_gate_dropped: dict[str, int]


def _build_and_write_loot(
    build_dir: Path,
    fork: ForkDatabase,
    classification: LootClassification,
    overlay_dir: Path,
    curated_dir: Path,
) -> _LootRun:
    """loot.json from the committed inputs plus `classification`, the one
    code path `loot` and `loot-merge` share, so the same inputs always
    write the same loot.json. Also writes items.json's `superseded_by` and
    narrows quest-only rows in items/<class>.json, both of which read the
    finished document."""
    zone_rows = json.loads((build_dir / "zones.json").read_text(encoding="utf-8"))
    item_rows = json.loads((build_dir / "items.json").read_text(encoding="utf-8"))
    build_items = {int(row["id"]) for row in item_rows}
    item_inventory_types = {int(row["id"]): int(row["inventory_type"]) for row in item_rows}
    # wowhead-world-drops lane, 2026-09-29: `wowhead_additions`' level-range
    # fallback, for when wowhead's `dropped-by` rows state no creature level.
    item_required_levels = {
        int(row["id"]): int(row.get("required_level") or 0) for row in item_rows
    }
    # Every cache below is committed and read offline (never fetched here):
    # quest levels (`quest-levels`), wowhead item sources (`item-sources`),
    # the classic-db dump parse and its recipe/reagent chain
    # (`fetch-classic-sources`).
    item_sources = load_item_sources(build_dir)
    classic_sources = load_classic_sources(build_dir)
    classic_crafted = load_classic_crafted_recipes(build_dir)

    # Contract 10.4's build filter and its pruning sweep happen inside
    # build_loot, BEFORE the overlay, so a curated source with a
    # deliberately empty item list (an announced, unlooted raid) survives.
    document, stats = build_loot(
        fork,
        {int(row["id"]): row["name"] for row in zone_rows},
        loot_instance_types(classification),
        _pvp_ranks_with_classic_db(build_dir, classification.pvp_ranks, item_rows),
        build_items,
        item_inventory_types,
        load_quest_levels(build_dir),
        item_sources,
        classic_sources,
        zone_rows,
        item_required_levels,
    )
    # Splits every `pvp` source into alliance/horde copies BEFORE
    # re-itemisation, so a re-itemised item copied onto a classic twin's
    # source lands in the twin's already-split bucket.
    document, pvp_faction_stats = split_pvp_sources_by_faction(
        document,
        {int(row["id"]): row["name"] for row in item_rows},
        classic_sources,
        zone_rows,
        not_rank_rewards=_classic_unranked(build_dir),
    )
    # A Forever-new item still wholly unsourced inherits its classic
    # namesake's sources; then a legacy id listed next to its replacement
    # is deduplicated. Both run before the overlay so a curated fact wins.
    document, reitemised = apply_reitemisation(document, item_rows)
    superseded = superseded_pairs(document, item_rows)
    document, superseded_removed = apply_supersession(document, superseded)
    document = apply_overlays(document, load_overlays(overlay_dir))
    # Content phases after the overlay and before the quest turn-in gate, so
    # a quest whose turn-in item is gated is gated too.
    document, _ = apply_content_phases(document, load_content_phases(curated_dir))
    # The quest gate needs the overlay's raid `opens`; the crafted gate needs
    # the quest gate's; the vendor-cost gate reads whatever both left open.
    document = apply_quest_opens_gate(document, classic_sources)
    document = apply_crafted_opens_gate(document, classic_crafted)
    item_levels = {int(row["id"]): int(row.get("item_level") or 0) for row in item_rows}
    item_qualities = {int(row["id"]): int(row.get("quality") or 0) for row in item_rows}
    document, vendor_cost_gated = apply_vendor_cost_gate(
        document, item_sources, build_items, item_levels, item_qualities
    )
    # Task L1.7: every boss row's creature rank, once the rows are final.
    rare_spawns = load_rare_spawns(build_dir)
    document = apply_npc_ranks(
        document,
        load_npc_ranks(build_dir),
        rare_spawns,
        rare_spawn_names(classic_sources, rare_spawns),
    )
    write_document(document, build_dir / LOOT)
    return _LootRun(
        document=document,
        stats=stats,
        pvp_faction_stats=pvp_faction_stats,
        reitemised=reitemised,
        superseded=superseded,
        superseded_removed=superseded_removed,
        vendor_cost_gated=vendor_cost_gated,
        superseded_marked=mark_superseded_items(build_dir, superseded),
        quest_class_gate_dropped=apply_quest_class_gate_to_class_items(build_dir, document),
    )


def _log_loot_run(command: str, run: _LootRun) -> None:
    logger.info(
        "%s: %d sources naming %d items (%d from classic-db, %d from wowhead, %d from "
        "re-itemisation inheritance, %d quests with faction detail); pvp faction split: "
        "%d via classic-db vendor, %d via title, %d unresolved and dropped; %d fork ids "
        "left out because this build has no such item, %d fork entries with no kind "
        "dropped, %d zone sources naming a zone zones[] does not, %d bosses dropped for "
        "having no name in either database; %d superseded rows marked (%d source/boss "
        "listings deduplicated); %d quest-only rows dropped for excluding their own class "
        "across %d classes; %d vendor rows gated to opens=later",
        command,
        len(run.document.sources),
        run.stats.items,
        run.stats.classicdb_items,
        run.stats.wowhead_items,
        run.reitemised,
        len(run.document.quests),
        run.pvp_faction_stats.resolved_vendor,
        run.pvp_faction_stats.resolved_title,
        len(run.pvp_faction_stats.unresolved),
        run.stats.absent_items,
        run.stats.dropped_entries,
        run.stats.unnamed_zones,
        run.stats.dropped_unnamed_bosses,
        run.superseded_marked,
        run.superseded_removed,
        sum(run.quest_class_gate_dropped.values()),
        len(run.quest_class_gate_dropped),
        run.vendor_cost_gated,
    )


def _class_item_files(build_dir: Path) -> list[Path]:
    return [build_dir / "items.json", *sorted((build_dir / "items").glob("*.json"))]


def write_loot_files(
    build: str,
    engine_dir: Path,
    root: Path = Path("builds"),
    overlay_dir: Path = Path("curated/loot"),
    curated_dir: Path = Path("curated"),
    ids_md: Path = IDS_MD,
    *,
    allow_shrink: bool = False,
) -> list[Path]:
    """`python -m pipeline loot`: everything this module's doc lists, from
    the build's raw client tables. It writes the instance types and PvP
    ranks it read to `raw/client/loot-classification.json` first, so
    `loot-merge` builds loot.json from the same facts.

    `allow_shrink` does nothing: `normalize` owns the catalogue-shrink gate
    (`check_item_sparse_completeness`). It stays because data.yml passes the
    one `--allow-shrink` to both commands."""
    del allow_shrink
    build_dir = root / build
    raw = build_dir / "raw"
    if not raw.exists():
        raise SystemExit(f"no raw data at {raw}; run `python -m pipeline fetch` first")
    for name in ("zones.json", "items.json", "spells.json"):
        _require(build_dir / name, "normalize")
    fork = load_fork_database(engine_dir)
    # The same guard normalize runs: a socketed item would get a loot table
    # for gear the rest of the repository cannot model.
    check_no_sockets(read_csv(raw / "ItemSparse.csv"), build)
    zone_rows = json.loads((build_dir / "zones.json").read_text(encoding="utf-8"))
    classification = classification_from_raw(raw, zone_rows)
    classification_path = write_classification(build_dir, classification)

    run = _build_and_write_loot(build_dir, fork, classification, overlay_dir, curated_dir)

    enchants = build_enchants(fork)
    suffixes = build_suffixes(fork)
    client, icon_for = client_tables(build_dir, raw)
    simbuffs = build_simbuffs(
        ids_md_ids(ids_md.read_text(encoding="utf-8")),
        fork_tables(fork) + client,
        load_overrides(curated_dir),
        icon_for,
    )
    write_records(enchants, build_dir / ENCHANTS)
    write_records(suffixes, build_dir / SUFFIXES)
    write_document(simbuffs, build_dir / SIMBUFFS)
    with_suffixes, restricted = apply_fork_columns(
        build_dir, suffix_options(fork), faction_restrictions(fork)
    )
    weapons_won = apply_fork_weapon_damage(build_dir, fork_weapon_damage(fork))

    _log_loot_run("loot", run)
    logger.info(
        "loot: %d enchants, %d suffixes, %d buff ids; items.json: %d with suffix options, "
        "%d faction-restricted; items/*.json: %d weapon rows won by the fork's own damage",
        len(enchants),
        len(suffixes),
        len(simbuffs.entries),
        with_suffixes,
        restricted,
        weapons_won,
    )
    refresh_manifest(build_dir)
    return [
        classification_path,
        build_dir / LOOT,
        build_dir / ENCHANTS,
        build_dir / SUFFIXES,
        build_dir / SIMBUFFS,
        *_class_item_files(build_dir),
    ]


def merge_loot_files(
    build: str,
    engine_dir: Path,
    root: Path = Path("builds"),
    overlay_dir: Path = Path("curated/loot"),
    curated_dir: Path = Path("curated"),
) -> list[Path]:
    """`python -m pipeline loot-merge`: loot.json alone, from committed
    inputs only -- the engine fork checkout, zones.json, items.json, the
    raw/ caches and `raw/client/loot-classification.json`, which the last
    full `loot` run wrote from the client's Map.csv and ItemSparse.csv. It
    runs `loot`'s own loot.json code on those, so on the same inputs the
    two commands write the same loot.json.

    Besides loot.json it writes what reads the finished document (items.json's
    `superseded_by`, the quest-only narrowing of items/<class>.json) and
    names any buff id IDS.md gained since the last full run; enchants,
    suffixes and the fork weapon columns wait for the next full run."""
    build_dir = root / build
    for name in ("zones.json", "items.json"):
        _require(build_dir / name, "normalize")
    classification = load_classification(build_dir)
    fork = load_fork_database(engine_dir)
    run = _build_and_write_loot(build_dir, fork, classification, overlay_dir, curated_dir)
    # An engine buff id IDS.md gained since the last full rebuild (a raid
    # aura the fork added) must be named before the site can show it, and
    # the full rebuild only runs on a night wowhead fetched; name it from
    # the fork's own tables here, keeping every committed entry as it is.
    committed_simbuffs = load_simbuffs(build_dir)
    if committed_simbuffs:
        name_tables = fork_tables(fork)
        if all((build_dir / "raw" / name).exists() for name in CLIENT_NAME_TABLES):
            name_tables += client_tables(build_dir, build_dir / "raw")[0]
        simbuffs = merge_simbuffs(
            ids_md_ids(IDS_MD.read_text(encoding="utf-8")),
            name_tables,
            committed_simbuffs,
            load_overrides(curated_dir),
        )
        write_document(simbuffs, build_dir / SIMBUFFS)
    _log_loot_run("loot-merge", run)
    refresh_manifest(build_dir)
    return [
        build_dir / LOOT,
        *([build_dir / SIMBUFFS] if committed_simbuffs else []),
        *(_class_item_files(build_dir) if run.superseded or run.quest_class_gate_dropped else []),
    ]
